#
#   TOL_Y_DOWN   手指保留   掌心核心   小臂保留   影子带去掉了
#      120        96.9%      100%      99.0%      45%
#       90        96.9%      100%      97.2%      57%
#       75        82.2%      100%      92.2%      79%   <-- 当前值，拐点
#       60        72.7%      100%      80.4%      83%
#       40        60.6%      100%      69.8%      90%
