# 识别骨架：截前臂 -> 找指尖 -> 找指缝 -> 指根
# ===========================================================================
def _to_local_points(points, origin, up, scale) -> np.ndarray:
    """把点转到手部局部坐标系并按 R 归一化。

    x 为手掌左右方向，**y 为指向手腕为正**（所以指尖的 y 为负）。
    """
    pts = np.asarray(points, dtype=np.float64).reshape(-1, 2)
    if pts.size == 0:
        return np.zeros((0, 2), dtype=np.float64)
    right = np.array([-float(up[1]), float(up[0])], dtype=np.float64)
    delta = pts - np.asarray(origin, dtype=np.float64).reshape(1, 2)
    safe = float(scale) if abs(float(scale)) > 1e-6 else 1.0
    return np.stack([delta @ right / safe, -(delta @ up) / safe], axis=1)


def _contour_point(contour, index) -> np.ndarray:
    """按环形索引取轮廓点（float64）。"""
    count = int(contour.shape[0])
    return contour[int(index) % count].reshape(2).astype(np.float64)


def _turning_ratio(contour, index: int, window: int) -> float:
    """轮廓在该点的「转折比」= 弯曲深度 / 弦长。

    直线段接近 0，指尖圆帽明显更大。**不依赖像素尺度**，所以不用绝对阈值。
    """
    here = _contour_point(contour, index)
    before = _contour_point(contour, index - window)
    after = _contour_point(contour, index + window)
    chord = after - before
    chord_length = float(np.linalg.norm(chord))
    if chord_length < 1e-6:
        return 0.0
    offset = here - before
    perpendicular = abs(float(offset[0] * chord[1] - offset[1] * chord[0])) / chord_length
    return float(np.clip(perpendicular / chord_length, 0.0, 1.0))


def _contour_angle(contour, index: int, window: int) -> float:
    """轮廓在该点的夹角（度）。越接近 180 越平，越小越尖。"""
    here = _contour_point(contour, index)
    before = _contour_point(contour, index - window) - here
    after = _contour_point(contour, index + window) - here
    na = float(np.linalg.norm(before))
    nb = float(np.linalg.norm(after))
    if na < 1e-6 or nb < 1e-6:
        return 180.0
    cos_value = float(np.clip(np.dot(before, after) / (na * nb), -1.0, 1.0))
    return float(np.degrees(np.arccos(cos_value)))


def _tip_sharpness(contour, index: int, window: int) -> tuple:
    """多尺度地量"这里尖不尖"，返回（转折比, 夹角）。"""
    windows = [max(2, int(round(window * factor)))
               for factor in (0.6, 1.0, 1.5)]
    ratios = [_turning_ratio(contour, index, w) for w in windows]
    angles = [_contour_angle(contour, index, w) for w in windows]
    # 小窗口看得到指尖圆帽的明显弯曲，大窗口会把它平均掉：
    # 所以转折比取最尖的读数，夹角取中位数（更稳）
    return float(np.max(ratios)), float(np.median(angles))


def _sample_plane(plane: np.ndarray, point: np.ndarray) -> float:
    """取某个浮点坐标处的像素值（就近取整，越界夹回）。"""
    height, width = plane.shape[:2]
    x = int(np.clip(round(float(point[0])), 0, width - 1))
    y = int(np.clip(round(float(point[1])), 0, height - 1))
    return float(plane[y, x])


def _protrusion_length(thickness: np.ndarray, tip_point, palm_center,
                       radius: float) -> float:
    """量"这根东西从指尖凸出来了多长"，按 R 归一化。

    做法：从指尖沿直线朝掌心走，一路采样内部距离变换的厚度值，
    找到**第一个"厚度 >= RECOG_TIP_PALM_THICK * R"** 的位置 —— 那里就算
    已经进入掌区了。指尖到那里的距离就是凸出长度。

    为什么需要它：真手指（哪怕小指这种很短的）都是一条**细长凸出**，
    而拳头的指节凸起是**圆钝鼓包** —— 一出指尖厚度就上去了。
    这个量是尺度无关的（按 R 归一化），而且语义正好就是"手指伸出来多少"。
    """
    tip = np.asarray(tip_point, dtype=np.float64).reshape(2)
    palm = np.asarray(palm_center, dtype=np.float64).reshape(2)
    total = float(np.linalg.norm(palm - tip))
    if total < 1e-6:
        return 0.0
    steps = int(np.clip(total, 8, 400))
    fractions = np.linspace(0.0, 1.0, steps)
    xs = tip[0] + (palm[0] - tip[0]) * fractions
    ys = tip[1] + (palm[1] - tip[1]) * fractions
    height, width = thickness.shape[:2]
    xi = np.clip(np.round(xs).astype(np.int32), 0, width - 1)
    yi = np.clip(np.round(ys).astype(np.int32), 0, height - 1)
    values = thickness[yi, xi]                 # 向量化取样，比逐点循环快得多
    hit = np.nonzero(values >= float(RECOG_TIP_PALM_THICK) * float(radius))[0]
    if hit.size == 0:
        return total / float(radius)           # 一路都没变厚 -> 整条都是凸出
    return float(fractions[int(hit[0])]) * total / float(radius)


def _estimate_arm_direction(mask: np.ndarray, palm_center, radius: float):
    """★ **方向无关**地找【小臂的指向】（单位向量，从掌心指向小臂）。

    ⚠️⚠️ 为什么必须有这个函数：
      原来的 ``_estimate_wrist()`` 只按**水平行**量宽度、并且**只在掌心下方**找束腰
      —— 等于写死了"**小臂从画面下方垂直入画**" ✗
      第四批素材（FPGA 摄像头实拍）是**小臂从右侧水平伸入**的，
      于是它找了个毫无意义的行 -> 掌轴错 ~90° -> **所有角度判据全部错位** ✗
      （实测：shot_25 是"点赞"，掩膜是个完美的点赞剪影，却判成了"食指"）

    ★ 怎么做到方向无关 —— 用"**粗细**"来认小臂，而不是用"方向"：
        · 小臂是**细长**的，全宽只有 ~1.0~1.8R
        · 手指更细（~0.3~0.5R），但**没那么长**（指尖到 2.7~3.0R 就没了）
        · 手掌更粗（~2R 以上）
      所以：从掌心向 360° 各个方向走，找那个「**走得远、而且一路都不太粗**」的方向 ✓
      小臂能一直走到画面边缘，比手指走得远，于是胜出 ✓

    拿不到（比如画面里没有小臂）时返回 None，调用方退回老做法 ✓
    """
    height, width = mask.shape[:2]
    center = np.asarray(palm_center, dtype=np.float64).reshape(2)
    R = float(radius)
    if R <= 1e-6:
        return None
    dt = cv2.distanceTransform(mask, cv2.DIST_L2, 5)

    w_max = float(RECOG_ARM_WIDTH_MAX_R) * R          # 超过这个全宽就不算小臂
    w_min = float(RECOG_ARM_WIDTH_MIN_R) * R          # 小于这个全宽也不算（那是手指）
    r_start = float(RECOG_ARM_SEARCH_R_MIN) * R        # 从掌外一点开始（掌内必然太粗）
    r_end = float(RECOG_ARM_SEARCH_R_MAX) * R
    step = max(2.0, 0.06 * R)

    best_dir, best_reach = None, 0.0
    min_run = float(RECOG_ARM_MIN_LEN_R) * R           # 需要多长的一段"中等宽度"
    for ang_deg in range(0, 360, int(RECOG_ARM_ANGLE_STEP)):
        t = float(np.radians(ang_deg))
        d = np.array([np.cos(t), np.sin(t)], dtype=np.float64)
        # 这个方向"画面允许走多远"（射线到边框的距离）
        to_border = _ray_to_border(center, d, width, height)
        if to_border < 0.8 * R:
            continue                                    # 方向太贴着边框，没意义
        # ★★ 判据（两条都要满足）★★
        #  ① 累积一段够长的「中等宽度」（小臂 1.0~1.8R；手指只有 0.3~0.5R ✗）
        #     沿"掌心->手腕->小臂"走，宽度是 粗(掌) -> 细(手腕) -> 中(小臂)，
        #     所以不能要求"一路都不细"（手腕就细 ✗），要**累积**。
        #  ② ★ 必须走到「该方向画面允许距离的 82% 以上」★
        #     ⚠️ 这一条是关键：小臂一定是**被画面切断**的（走到边缘），
        #        而手指只伸到 2.7~3.0R 就停了 —— 差距很大，特别干净 ✓
        #     实测：只用判据① 时，张开的手指（比如手枪的拇指+食指）也满足宽度带 ✗
        #           于是把手指当小臂 -> 转了 +96° 而不是 −90° -> 上下颠倒 ✗
        run = 0.0
        best_run = 0.0
        reach = 0.0
        r = r_start
        while r <= r_end:
            p = center + d * r
            x, y = int(round(p[0])), int(round(p[1]))
            if x < 0 or y < 0 or x >= width or y >= height:
                reach = r
                break                                   # 出画面
            if mask[y, x] == 0:
                break                                   # 断了：手和小臂是连续的
            w_now = 2.0 * float(dt[y, x])               # 该处全宽（像素）
            if w_now > w_max:
                run = 0.0                               # 还在手掌里
            elif w_now >= w_min:
                run += step                             # 中等宽度：像小臂
                if run > best_run:
                    best_run = run
            else:
                run = 0.0                               # 细：手腕或手指
            reach = r
            r += step
        if reach < float(RECOG_ARM_BORDER_FRAC) * to_border:
            continue                                    # ★ 没走到画面的足够远处
        if best_run < min_run:
            continue
        if reach > best_reach:
            best_reach, best_dir = reach, d
    if best_dir is None:
        return None
    return best_dir, best_reach


def _ray_to_border(center, direction, width: int, height: int) -> float:
    """从 ``center`` 沿 ``direction`` 出发，到画面边框的距离（像素）。"""
    ts = []
    dx, dy = float(direction[0]), float(direction[1])
    if dx > 1e-9:
        ts.append((width - 1 - float(center[0])) / dx)
    elif dx < -1e-9:
        ts.append((0.0 - float(center[0])) / dx)
    if dy > 1e-9:
        ts.append((height - 1 - float(center[1])) / dy)
    elif dy < -1e-9:
        ts.append((0.0 - float(center[1])) / dy)
    ts = [t for t in ts if t > 0.0]
    return float(min(ts)) if ts else 0.0


def _estimate_wrist(mask: np.ndarray, palm_center, radius: float):
    """手腕 W = 手掌**下方**横截面最窄的那一行。

    ★★ 这里**故意写死"小臂从画面下方垂直入画"** ★★
      因为整条流水线（截前臂、掌轴、所有角度判据）都是围绕这个前提标定的，
      而它在"手指朝上"的图上经过验证（老三批 28 张就是靠它）✓

      手转到别的方向怎么办？**不在这里做** —— 由前处理
      ``detect_hand_rotation()`` 先把画面**转成"手指朝上"**，再进这条流水线 ✓
      （试过让这里"方向无关"，实测反而更差：手大、小臂被画面切掉时
        "找走得远又细的方向"会误选到手指 ✗）

    ⚠️ 早期那版（已删除的 solution.py）用的是"手部底端带状区域的质心"，但那个做法
    默认掩膜在手腕处就结束了 —— 而我们的掩膜里含**整条小臂**，所以底端质心
    取到的是小臂尖，实测跑到 (1522,1265)，离真正的手腕差了 400 多像素。

    改成找**宽度剖面的局部极小**：手掌往下、宽度会先收到最窄（手腕束腰），
    再进小臂又变宽。取那个"离掌心最近的、明显比最宽处窄的"局部极小即可。

    ``mask`` 必须是**含小臂**的（截断之前），否则找不到束腰。
    """
    return _estimate_wrist_legacy(mask, palm_center, radius)


def _estimate_wrist_by_arm(mask: np.ndarray, palm_center, radius: float):
    """方向无关地估手腕：先找小臂指向（``_estimate_arm_direction``），再沿它找最细处。"""
    center = np.asarray(palm_center, dtype=np.float64).reshape(2)
    R = float(radius)
    got = _estimate_arm_direction(mask, center, R)
    if got is None:
        return None
    arm_dir, reach = got

    dt = cv2.distanceTransform(mask, cv2.DIST_L2, 5)
    step = max(2.0, 0.05 * R)
    best_r, best_w = None, None
    # ★★ 找手腕束腰【只在掌后很近的一段里找】★★
    #   ⚠️ 踩过的坑：原来用 RECOG_ARM_SEARCH_R_MIN(0.85R) ~ RECOG_ARM_WRIST_R_MAX(3.20R)，
    #      结果找到的是**很远的臂尖**，腕距离跑到 2.70~3.15R ✗
    #      实测证据（同一张图 shot_07，掩膜像素/R/检出指尖数两边完全一样）：
    #          原样（手指朝左）      -> 腕距离 2.70R -> 判定 MR  ✗
    #          顺时针转 90（手指朝上）-> 腕距离 1.27R -> 判定 IR  ✓
    #      分歧就是从这一行开始的 —— 它是唯一的"旋转依赖"来源 ✓
    #      手腕束腰就在手掌后面一点点（实测 1.0~1.5R），根本不该去 3R 外找 ✓
    r = float(RECOG_WRIST_NEAR_R_MIN) * R
    while r <= min(reach, float(RECOG_WRIST_NEAR_R_MAX) * R):
        p = center + arm_dir * r
        x, y = int(round(p[0])), int(round(p[1]))
        if 0 <= x < mask.shape[1] and 0 <= y < mask.shape[0] and mask[y, x]:
            w = float(dt[y, x])
            if best_w is None or w < best_w:
                best_w, best_r = w, r
        r += step
    if best_r is None:
        return None
    wrist = center + arm_dir * best_r
    if float(np.linalg.norm(wrist - center)) < 0.4 * R:
        return None
    return wrist.astype(np.float64)


def _estimate_wrist_legacy(mask: np.ndarray, palm_center, radius: float):
    """手腕 W = 手掌下方**横截面最窄**的那一行（老做法，**只适合小臂垂直入画**）。

    ⚠️ 保留它只作为兜底：当画面里找不到"细长的小臂"（比如手伸到画面外、
    或者掩膜没含小臂）时用它。**不要再把它当主路径** —— 它写死了小臂方向 ✗

    原始注释（仍然有效）：早期那版用的是"手部底端带状区域的质心"，
    但那个做法默认掩膜在手腕处就结束了 —— 而我们的掩膜里含**整条小臂**，
    所以底端质心取到的是小臂尖。改成找**宽度剖面的局部极小**。
    """
    height, width = mask.shape[:2]
    row_widths = np.count_nonzero(mask, axis=1)
    rows = np.nonzero(row_widths)[0]
    if rows.size == 0:
        return None
    bottom_row = int(rows[-1])
    cy = int(round(float(palm_center[1])))

    # 只从掌心下方约 0.8R 处开始找（再往上就是手掌本身，不是束腰）
    start = min(bottom_row, cy + int(round(0.8 * float(radius))))
    if bottom_row - start < 3:
        return None
    segment = row_widths[start:bottom_row + 1].astype(np.float32)
    if segment.size < 3:
        return None

    # 先平滑，免得单行的椒盐噪声当选
    kernel = max(3, int(round(0.20 * float(radius))) | 1)
    smoothed = cv2.blur(segment.reshape(-1, 1), (1, kernel)).ravel()
    peak = float(smoothed.max())
    if peak <= 0.0:
        return None

    left = np.concatenate([[smoothed[0]], smoothed[:-1]])
    right = np.concatenate([smoothed[1:], [smoothed[-1]]])
    is_min = (smoothed <= left) & (smoothed <= right) & (smoothed < 0.88 * peak)
    candidates = np.nonzero(is_min)[0]
    # 有束腰就取离掌心最近的那个；没有就退回"整段最窄的一行"
    best = int(candidates[0]) if candidates.size else int(np.argmin(smoothed))
    wrist_row = start + best

    xs = np.nonzero(mask[wrist_row])[0]
    if xs.size < int(RECOG_WRIST_MIN_PIXELS):
        return None
    center = np.array([0.5 * (float(xs.min()) + float(xs.max())), float(wrist_row)],
                      dtype=np.float64)
    # 手腕必须确实在掌心下方，否则说明定位有问题
    if center[1] <= float(palm_center[1]):
        return None
    return center


def _truncate_forearm(mask: np.ndarray, palm_center, up, radius: float) -> np.ndarray:
    """前臂截断：只保留"掌心 + 手指那一侧"的**半平面**。

    ⚠️ 这里踩过一个严重的坑，务必保留这个写法：
       最初把多边形边距写成 `4R`（约 594 px）。结果多边形在**手指方向**也只
       延伸了 594 px，而指尖离截断线有 601 px —— **整片指尖被削平了**。
       表现在掩膜上就是出现一条水平直边，那条直边上的毛刺被当成了 4 个"指尖"，
       于是指尖数从 5 变成 6，而且指根/长度全乱。
       判据：手指区每行游程数在 y=330~390 全是 0，y=400 才突然冒出 3~5 个。

       所以沿**两个方向**都要延伸到远大于图像尺寸 —— 等价于一个半平面，
       这样无论手举多高、指尖离掌心多远都不会被误切。
    """
    height, width = mask.shape[:2]
    far = float(max(height, width)) * 2.0     # 远大于图像，保证覆盖整个手指侧
    origin = np.asarray(palm_center, dtype=np.float64) - \
        np.asarray(up, dtype=np.float64) * (float(RECOG_TRUNCATE_FACTOR) * float(radius))
    along = np.array([-float(up[1]), float(up[0])], dtype=np.float64)
    polygon = np.array([
        origin + along * far,
        origin - along * far,
        origin - along * far + np.asarray(up) * far,
        origin + along * far + np.asarray(up) * far,
    ], dtype=np.int32)
    allowed = np.zeros((height, width), dtype=np.uint8)
    cv2.fillConvexPoly(allowed, polygon, 255)
    return cv2.bitwise_and(mask, allowed)


def _detect_fingertips(contour, mask: np.ndarray, palm_center, radius: float, up):
    """在轮廓上找指尖。返回（候选列表, 距离剖面）。

    判据（全部按 R 归一化）：
      1. 到掌心的距离 >= 1.25R
      2. 是该距离剖面的**局部极大**（环形邻域窗口）
      3. **突出度**足够（极大值要比邻域低谷高出 >= 0.2R）
      4. 形态要"尖"：转折比够大，或夹角够小
      5. 内部厚度不能太厚（排除掌缘/前臂那种厚凸起）
      6. 必须落在**掌上方**（局部系里 y <= 0.15）
    """
    count = int(contour.shape[0])
    if count < 8:
        return [], None
    points = contour.reshape(count, 2).astype(np.float64)
    distances = np.linalg.norm(points - np.asarray(palm_center).reshape(1, 2), axis=1)

    window = max(2, int(round(RECOG_TIP_PEAK_WINDOW * float(radius))))
    idx = np.arange(count)
    floor_max = distances.copy()      # 环形邻域最大值
    floor_min = distances.copy()      # 环形邻域最小值（算突出度用）
    for offset in range(1, window + 1):
        np.maximum(floor_max, distances[(idx + offset) % count], out=floor_max)
        np.maximum(floor_max, distances[(idx - offset) % count], out=floor_max)
        np.minimum(floor_min, distances[(idx + offset) % count], out=floor_min)
        np.minimum(floor_min, distances[(idx - offset) % count], out=floor_min)

    # 先用纯向量化的三条门槛筛掉绝大多数轮廓点（快）
    keep = distances >= RECOG_TIP_MIN_DISTANCE * float(radius)
    keep &= floor_max <= distances + 1e-9
    keep &= (distances - floor_min) >= RECOG_TIP_MIN_PROMINENCE * float(radius)
    candidate_indices = np.nonzero(keep)[0]
    if candidate_indices.size == 0:
        return [], distances

    # 剩下少数候选才算形态和厚度（贵的那部分）
    thickness = cv2.distanceTransform(mask, cv2.DIST_L2, 5)
    candidates = []
    for raw_index in candidate_indices:
        index = int(raw_index)
        ratio, angle = _tip_sharpness(contour, index, window)
        inner = points[index] + (np.asarray(palm_center) - points[index]) * \
            float(RECOG_TIP_THICKNESS_SAMPLE)
        thickness_ratio = _sample_plane(thickness, inner) / float(radius)
        if ratio < RECOG_TIP_MIN_TURN_RATIO and \
                thickness_ratio > RECOG_TIP_THICKNESS_MAX:
            continue
        if angle > RECOG_TIP_MAX_ANGLE_DEG:
            continue
        # 针状毛刺：夹角和厚度同时极端小 -> 不是指尖（真指尖是圆帽，两者都不会这么极端）
        if angle < RECOG_TIP_MIN_ANGLE_DEG and \
                thickness_ratio < RECOG_TIP_MIN_THICKNESS:
            continue
        # ★主力判据：凸出长度。真手指是细长凸出，指节凸起是圆钝鼓包。
        #   这一条同时管住了两头 —— 既排掉拳头的指节凸起，又保住很短的小指。
        protrusion = _protrusion_length(thickness, points[index], palm_center, radius)
        if protrusion < float(RECOG_TIP_PROTRUSION_MIN):
            continue
        candidates.append({
            "point": points[index].copy(),
            "distance": float(distances[index]),
            "turn_ratio": float(ratio),
            "angle_deg": float(angle),
            "thickness_ratio": float(thickness_ratio),
            "protrusion_ratio": float(protrusion),
        })

    # 去重：距离太近的是同一个指尖，留离掌心更远的那个
    candidates.sort(key=lambda item: -item["distance"])
    merged = []
    for item in candidates:
        if any(float(np.linalg.norm(item["point"] - kept["point"]))
               < RECOG_TIP_DEDUP * float(radius) for kept in merged):
            continue
        merged.append(item)
        if len(merged) >= int(RECOG_TIP_MAX_COUNT):
            break

    # 过滤：指尖必须落在掌上方（局部系 y <= 阈值）。
    # 这一步同时把"前臂截断留下的两个直角"清掉 —— 它们在掌心下方。
    result = []
    for item in merged:
        local = _to_local_points(item["point"].reshape(1, 2),
                                 palm_center, up, radius)[0]
        if float(local[1]) > float(RECOG_TIP_PALM_SIDE_MAX):
            continue
        item["local"] = (float(local[0]), float(local[1]))
        result.append(item)

    # 按相对掌心的极角排序，显示时就是 1,2,3...
    result.sort(key=lambda item: float(np.arctan2(item["local"][1], item["local"][0])))
    return result, distances


def _detect_gaps(contour, tips, palm_center, radius: float, up):
    """在每一对**相邻指尖**之间找最深的凹谷，就是指缝。

    找法：取两个指尖之间那段轮廓，找其中**离掌心最近**的那个点 ——
    它天然落在两指之间的谷底。深度用"该点到两指尖连线的垂距"来算，
    含义和凸缺陷深度一致。
    """
    if len(tips) < 2 or contour is None:
        return []
    count = int(contour.shape[0])
    points = contour.reshape(count, 2).astype(np.float64)
    palm_distances = np.linalg.norm(points - np.asarray(palm_center).reshape(1, 2), axis=1)
    gaps = []
    for first, second in zip(tips, tips[1:]):
        first_point = np.asarray(first["point"], dtype=np.float64)
        second_point = np.asarray(second["point"], dtype=np.float64)
        first_index = int(np.argmin(np.linalg.norm(points - first_point.reshape(1, 2), axis=1)))
        second_index = int(np.argmin(np.linalg.norm(points - second_point.reshape(1, 2), axis=1)))
        forward = (second_index - first_index) % count
        backward = (first_index - second_index) % count
        if forward <= backward:
            indices = [(first_index + step) % count for step in range(forward + 1)]
        else:
            indices = [(first_index - step) % count for step in range(backward + 1)]
        if len(indices) < 3:
            continue
        arc = points[indices]
        arc_distances = palm_distances[indices]
        inner = slice(1, -1)
        best = int(np.argmin(arc_distances[inner])) + 1
        valley = arc[best]
        chord = second_point - first_point
        span = float(np.linalg.norm(chord))
        if span < 1e-6:
            continue
        depth = abs(float(np.cross(chord / span, valley - first_point)))
        if depth < RECOG_GAP_MIN_DEPTH * float(radius):
            continue
        local = _to_local_points(valley.reshape(1, 2), palm_center, up, radius)[0]
        local_first = _to_local_points(first_point.reshape(1, 2), palm_center, up, radius)[0]
        local_second = _to_local_points(second_point.reshape(1, 2), palm_center, up, radius)[0]
        # 凹谷处"两指尖"张开的夹角。局部坐标系只是旋转+缩放，角度和图像里一致。
        v1 = np.asarray(local_first, dtype=np.float64) - np.asarray(local, dtype=np.float64)
        v2 = np.asarray(local_second, dtype=np.float64) - np.asarray(local, dtype=np.float64)
        n1 = float(np.linalg.norm(v1))
        n2 = float(np.linalg.norm(v2))
        if n1 < 1e-6 or n2 < 1e-6:
            continue
        angle = float(np.degrees(np.arccos(
            float(np.clip(np.dot(v1, v2) / (n1 * n2), -1.0, 1.0)))))
        if angle > RECOG_GAP_MAX_ANGLE_DEG:
            continue
        gaps.append({
            "point": valley.copy(),
            "local": (float(local[0]), float(local[1])),
            "depth_ratio": float(depth) / float(radius),
            "angle_deg": float(angle),
            "pair": (tuple(np.round(first_point).astype(int)),
                     tuple(np.round(second_point).astype(int))),
        })
    # ⚠️ 这里**不做按位置去重**。
    #    每条指缝都是"某一对相邻指尖"之间的谷，用的是轮廓上互不重叠的弧段，
    #    结构上就不可能重复。之前按 0.35R 做位置去重，实测把中间两条相邻的
    #    指缝（只差 20.8 px）误判成同一条给合并了 —— 5 指只剩 3 条缝。
    #    要去重也应该是"每对相邻指尖最多一条"，而这天然成立。
    gaps.sort(key=lambda item: float(np.arctan2(item["local"][1], item["local"][0])))
    return gaps[:int(RECOG_GAP_MAX_COUNT)]


def _build_fingers(tips, gaps, palm_center, radius: float, up):
    """给每根手指算「指根」：取它两侧指缝的中点。

    - 两侧都有指缝 -> 取中点
    - 只有一侧     -> 就用那一侧
    - 一侧都没有   -> 回退成"掌心沿该指尖方向 1.0R 处"
    指根到指尖连成一条线，就代表这根手指的**位置、方向、长度**。
    """
    fingers = []
    if not tips:
        return fingers
    for position, tip in enumerate(tips):
        tip_local = np.asarray(tip["local"], dtype=np.float64)
        # ⚠️ 两侧都要做上下界检查：指尖数通常比指缝数多一个（5 指 4 缝），
        #    直接写 gaps[position - 1] 会越界。
        left = gaps[position - 1]["point"] if 0 <= position - 1 < len(gaps) else None
        right = gaps[position]["point"] if 0 <= position < len(gaps) else None
        if left is not None and right is not None:
            base = (np.asarray(left, dtype=np.float64) +
                    np.asarray(right, dtype=np.float64)) / 2.0
        elif left is not None:
            base = np.asarray(left, dtype=np.float64)
        elif right is not None:
            base = np.asarray(right, dtype=np.float64)
        else:
            direction = np.asarray(tip["point"], dtype=np.float64) - np.asarray(palm_center)
            norm = float(np.linalg.norm(direction))
            direction = direction / norm if norm > 1e-6 else np.asarray(up, dtype=np.float64)
            base = np.asarray(palm_center, dtype=np.float64) + direction * float(radius)
        length = float(np.linalg.norm(np.asarray(tip["point"], dtype=np.float64) - base))
        fingers.append({
            "index": position + 1,
            "tip": np.asarray(tip["point"], dtype=np.float64).copy(),
            "base": base.copy(),
            "tip_local": (float(tip_local[0]), float(tip_local[1])),
            "length_ratio": length / float(radius),
            "angle_deg": float(np.degrees(np.arctan2(tip_local[1], tip_local[0]))),
        })
    return fingers


RECOG_AXIS_FROM_ARM = False        # ★ 掌轴优先用【前臂主轴】估计，而不是"掌心-手腕"
#   ⚠️ 为什么改这个（**前期处理的关键一步**）：
#     原来 up = 掌心 - 手腕，而"手腕"取的是**掩膜横截面最窄的那一行** ——
#     单行决策、很脆，实测掌轴误差能到 ±20°。而**所有角度判据都建立在 up 上** ✗
#
#   验证方法：张开的手里，**中指应当基本沿着掌轴**（解剖学事实）。
#   用 8 张含中指的素材、拿真值取出中指，量它相对掌轴的角度：
#        现用 up（掌心-手腕）：均值 -3.0°  标准差 12.4°  范围 -20.0°~+13.2°
#        前臂主轴（PCA）      ：均值 +3.4°  标准差  7.7°  范围  -3.1°~+23.5°
#   去掉同一个离群样本（gesture_05_busy）之后：
#        现用 up：标准差 11.6°          前臂主轴：标准差 **3.2°** ★
#   逐张看最清楚（04 / 05 / 05_s3 三张"张开的手"）：
#        现用 up  下中指 = -13.7° / -20.0° / -19.2°   ✗
#        前臂主轴 下中指 =  +0.4° /  +1.5° /  +4.2°   ✓✓
#
#   做法：前臂是一条细长带，取"沿 up 投影超过手腕"的像素做 PCA，主轴方向就是掌轴。
#         拿不到足够前臂像素时自动退回原来的手腕方向。


def _arm_principal_axis(mask: np.ndarray, palm_center, up, wrist):
    """用**前臂区域的主轴方向**估计掌轴（比"掌心-手腕"稳，见 RECOG_AXIS_FROM_ARM）。

    前臂区域 = 掩膜里"沿 up 的投影超过手腕"的那些像素。
    返回朝掌心方向的单位向量；像素不够时返回 None（调用方退回原做法）。
    """
    ys, xs = np.nonzero(mask)
    if xs.size < 64:
        return None
    pts = np.stack([xs, ys], axis=1).astype(np.float64)
    center = np.asarray(palm_center, dtype=np.float64).reshape(2)
    up = np.asarray(up, dtype=np.float64).reshape(2)
    proj = (pts - center[None, :]) @ up
    if wrist is not None:
        cut = float((np.asarray(wrist, dtype=np.float64).reshape(2) - center) @ up)
    else:
        cut = 60.0                      # 没有手腕估计时用个固定下限兜底
    sel = pts[proj > cut]
    if sel.shape[0] < 64:
        return None
    centroid = sel.mean(axis=0)
    delta = sel - centroid
    cov = (delta.T @ delta) / float(sel.shape[0])
    try:
        vals, vecs = np.linalg.eigh(cov)
    except np.linalg.LinAlgError:
        return None
    axis = vecs[:, int(np.argmax(vals))]
    norm = float(np.linalg.norm(axis))
    if norm < 1e-9:
        return None
    axis = axis / norm
    if float(axis @ up) < 0:            # 统一朝掌心方向
        axis = -axis
    return axis


def _recognize(mask: np.ndarray, state) -> Optional[dict]:
    """跑一遍识别骨架，返回结果字典；失败返回 None。"""
    if mask is None or int(np.count_nonzero(mask)) == 0:
        return None

    # 掌心 C 与尺度 R：优先用模式 4 已经算好的；没有就自己算一遍（兜底）
    # 兜底这条也走"闭运算副本"的稳健估法，理由同 RECON_PALM_CLOSE_RATIO 的注释。
    segment_stats = state.flags.get("segment_stats") or {}
    palm_center = segment_stats.get("palm_center")
    radius = segment_stats.get("palm_radius")
    if palm_center is None or not radius:
        palm_center, radius = _estimate_palm_robust(mask)
        if float(radius) < float(RECON_MIN_RADIUS_PX):
            return None
    palm_center = np.array([float(palm_center[0]), float(palm_center[1])], dtype=np.float64)
    radius = float(radius)

    # 手腕 -> 掌轴 -> 前臂截断
    wrist = _estimate_wrist(mask, palm_center, radius)
    if wrist is None:
        up = np.array([0.0, -1.0], dtype=np.float64)
    else:
        direction = palm_center - wrist
        norm = float(np.linalg.norm(direction))
        up = direction / norm if norm > 1e-6 else np.array([0.0, -1.0], dtype=np.float64)
    # ★ 用前臂主轴把掌轴精修一遍（实测标准差 12.4° -> 3.2°，见 RECOG_AXIS_FROM_ARM）
    arm_axis = None
    if RECOG_AXIS_FROM_ARM:
        arm_axis = _arm_principal_axis(mask, palm_center, up, wrist)
        if arm_axis is not None:
            up = arm_axis
    hand = _truncate_forearm(mask, palm_center, up, radius) if RECOG_MASK_TRUNCATE else mask
    if int(np.count_nonzero(hand)) == 0:
        hand = mask

    contours, _ = cv2.findContours(hand, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_NONE)
    if not contours:
        return None
    contour = max(contours, key=cv2.contourArea)
    if int(contour.shape[0]) < 8:
        return None

    tips, _profile = _detect_fingertips(contour, hand, palm_center, radius, up)
    gaps = _detect_gaps(contour, tips, palm_center, radius, up)
    fingers = _build_fingers(tips, gaps, palm_center, radius, up)

    # ---- 附加的"零成本"特征（都是现有数据的简单再加工）----

    # 1) 实心度 = 轮廓面积 / 凸包面积。
    #    手指之间的凹陷越多，实心度越低。
    #
    #    ★ 下面这组是**在本工程实测出来的**，不是从文献抄的
    #      （我一开始抄了文献的"张开 0.5~0.65"，实测对不上）：
    #        五指张开   0.69 ~ 0.70
    #        五指并拢   0.78        （用闭运算合成验证）
    #        握拳       0.88        （用掌核合成验证）
    #      合成姿态验证过它是**单调**的，方向正确。
    #      换环境/换人建议重新量一遍（见文件末尾的说明）。
    hull = cv2.convexHull(contour)
    contour_area = float(cv2.contourArea(contour))
    hull_area = float(cv2.contourArea(hull)) if hull is not None else 0.0
    solidity = float(np.clip(contour_area / hull_area, 0.0, 1.0)) if hull_area > 0 else 0.0

    # 2) 极角跨度 = 所有指尖极角所张的最小圆弧。
    #    五指并拢时各指尖极角接近（跨度小）；张开时跨度大（实测 86~92°）。
    #    用"环形跨度"算法，这样手转到大角度、角度跨过 ±180° 时也不会算错。
    #
    #    ⚠️ **手指数 <= 2 时这个值不可信，不要用**：
    #       实测"仿握拳"（只剩掌核）时检出的是轮廓凸点而不是真指尖，
    #       跨度反而算出 106.8°，比五指张开还大。
    #       它只在"确实有多根真手指"时才有意义。
    angle_span_deg = 0.0
    if len(tips) >= 2:
        tip_angles = np.array([float(np.arctan2(t["local"][1], t["local"][0]))
                               for t in tips], dtype=np.float64)
        ordered = np.sort(tip_angles)
        circular_gaps = np.diff(np.concatenate([ordered, [ordered[0] + 2.0 * np.pi]]))
        angle_span_deg = float(np.degrees(2.0 * np.pi - float(np.max(circular_gaps))))

    # 3) 掌心在 ROI 里的相对位置（0~1）。零成本，但能让"同一手势+不同位置"变成两条指令。
    if roi_enabled_now(state):
        rx0, ry0, rx1, ry1 = roi_rect_pixels((hand.shape[0], hand.shape[1]))
    else:
        rx0, ry0, rx1, ry1 = 0, 0, hand.shape[1], hand.shape[0]
    span_x = float(max(1, rx1 - rx0))
    span_y = float(max(1, ry1 - ry0))
    palm_rel = (float((palm_center[0] - rx0) / span_x),
                float((palm_center[1] - ry0) / span_y))

    # 4) 手指长度比的均值（单指的长度比在 fingers 里，这里顺手给个总览）
    mean_length = float(np.mean([f["length_ratio"] for f in fingers])) if fingers else 0.0

    # 5) 尺度 R 就是 radius，直接返回，不用另算。

    result = {
        "palm_center": palm_center,
        "palm_radius": radius,
        "wrist": wrist,
        "up": up,
        "hand_mask": hand,
        "contour": contour,
        "hull": hull,
        "solidity": solidity,
        "angle_span_deg": angle_span_deg,
        "palm_rel": palm_rel,
        "mean_length_ratio": mean_length,
        "tips": tips,
        "gaps": gaps,
        "fingers": fingers,
        "finger_count": len(tips),
    }
    # ★ 主输出：5 根手指各自的「伸开 / 蜷起」（径向剖面 + 模板匹配）
    #   顺序 = FINGER_NAMES = (拇指, 食指, 中指, 无名指, 小指)
    #   原来的 classify_gesture（数字标签）整套已删除，不再用。
    states, extensions, angles_used, match_detail, expect_len = _finger_states(
        hand, palm_center, up, radius, tips, gaps, contour=contour)
    result["finger_states"] = states                 # 5 个 bool（主判据：模板匹配）
    result["finger_extensions"] = extensions         # 5 个 float（× R），连续量
    result["finger_ray_angles"] = angles_used        # 5 个 float（度），画射线用
    result["finger_expect_len"] = expect_len         # 5 个 float（× R），模板预期长度
    result["finger_match"] = match_detail            # 匹配到的旋转/缩放/得分，调试用
    result["finger_names"] = list(FINGER_NAMES)
    result["finger_text"] = finger_states_text(states)
    return result


def _extend_along_ray(mask: np.ndarray, origin, direction, radius: float,
                      r_min: float, r_max: float, r_step: float) -> float:
    """沿一条射线量「从掌心往外连续有多长一段落在掩膜里」，返回长度（× R）。

    做法：从 r_min 走到 r_max 采样掩膜，找**与内端相连**的那一段连续命中，
    允许 ``FINGER_RUN_GAP_TOLERANCE`` 的小缺口（吞掉掩膜边缘的抖动），
    遇到更长的空洞就停 —— 这样孤立的小噪声块不会被当成手指。
    """
    height, width = mask.shape[:2]
    rs = np.arange(r_min, r_max + 1e-9, r_step, dtype=np.float64)
    xs = np.round(origin[0] + direction[0] * rs * radius).astype(np.int32)
    ys = np.round(origin[1] + direction[1] * rs * radius).astype(np.int32)
    inside = (xs >= 0) & (xs < width) & (ys >= 0) & (ys < height)
    hits = inside & (mask[np.clip(ys, 0, height - 1), np.clip(xs, 0, width - 1)] > 0)
    if hits.size == 0 or not bool(hits[0]):
        return 0.0
    gap_max = max(1, int(round(float(FINGER_RUN_GAP_TOLERANCE) / max(1e-9, r_step))))
    last_good = 0
    gap = 0
    for i in range(int(hits.size)):
        if hits[i]:
            gap = 0
            last_good = i
        else:
            gap += 1
            if gap > gap_max:
                break
    return float(rs[last_good])


def _radial_profile(mask: np.ndarray, palm_center, up, radius: float):
    """算**径向剖面**：每个角度上，掩膜从掌心往外连续延伸多长（× R）。

    返回 ``(angles_deg, profile)``，两个等长的一维数组。
    角度以掌轴为 0，**正方向 = 拇指侧**（右手 + 掌心朝镜头）。
    """
    up = np.asarray(up, dtype=np.float64).reshape(2)
    norm = float(np.linalg.norm(up))
    if norm > 1e-9:
        up = up / norm
    right = np.array([-up[1], up[0]], dtype=np.float64)   # 与 _to_local_points 一致
    origin = np.asarray(palm_center, dtype=np.float64).reshape(2)

    angles = np.arange(float(FINGER_PROFILE_MIN_DEG),
                       float(FINGER_PROFILE_MAX_DEG) + 1e-9,
                       float(FINGER_PROFILE_STEP_DEG), dtype=np.float64)
    r_step = max(1e-3, float(FINGER_PROBE_R_STEP))
    rs = np.arange(float(FINGER_PROBE_R_MIN),
                   float(FINGER_PROBE_R_MAX) + 1e-9, r_step, dtype=np.float64)

    # ---- 一次性算出所有 (角度, r) 采样点，向量化取掩膜值 ----
    t = np.radians(angles)[:, None]
    dirs = np.cos(t) * up[None, :] + np.sin(t) * right[None, :]        # (A, 2)
    pts = origin[None, None, :] + dirs[:, None, :] * (rs[None, :, None] * radius)
    height, width = mask.shape[:2]
    xs = np.round(pts[:, :, 0]).astype(np.int32)
    ys = np.round(pts[:, :, 1]).astype(np.int32)
    inside = (xs >= 0) & (xs < width) & (ys >= 0) & (ys < height)
    # Out-of-frame coordinates are empty, not repeated foreground border pixels.
    hits = inside & (mask[np.clip(ys, 0, height - 1), np.clip(xs, 0, width - 1)] > 0)

    # ---- 每条射线：从内端往外找"允许小缺口"的连续段 ----
    #   （逐角度循环 A≈116 次、每次 Rn≈54 步，实测 2~4 ms，可以接受）
    gap_max = max(1, int(round(float(FINGER_RUN_GAP_TOLERANCE) / r_step)))
    count_a, count_r = hits.shape
    profile = np.zeros(count_a, dtype=np.float64)
    for a in range(count_a):
        row = hits[a]
        if not bool(row[0]):
            continue
        last, gap = 0, 0
        for i in range(count_r):
            if row[i]:
                gap = 0
                last = i
            else:
                gap += 1
                if gap > gap_max:
                    break
        profile[a] = float(rs[last])
    return angles, profile


def _nominal_boundaries(combo):
    """给定槽位组合，返回它**期望有几条指缝、各自在哪**（名义横向位置，从拇指侧排到小指侧）。

    规则：把组合切成"连续段"；段内相邻两指之间有缝，段与段之间是一条"跨缝"，
    跨缝的位置取中间那几条名义缝的均值。
        例：{拇,食}          -> [T-I]                      = [+0.72]
            {拇,中}          -> [T-I 与 I-M 的均值]         = [+0.46]
            {食,中}          -> [I-M]                      = [+0.20]
            {拇,食,小}       -> [T-I, (I-M,M-R,R-P)的均值]  = [+0.72, -0.33]
    """
    runs = []
    for i in combo:
        if runs and i == runs[-1][-1] + 1:
            runs[-1].append(i)
        else:
            runs.append([i])
    out = []
    for idx, run in enumerate(runs):
        if idx > 0:
            prev = runs[idx - 1]
            vals = [float(FINGER_WEB_X[k]) for k in range(prev[-1], run[0])]
            if vals:
                out.append(sum(vals) / len(vals))
        for a, _b in zip(run, run[1:]):
            out.append(float(FINGER_WEB_X[a]))
    return out


def _segment_fingers_by_webs(hand_mask: np.ndarray, palm_center, up, radius: float):
    """★★★ 「先找指缝，再切段」—— 比"找指峰"稳得多的切入点 ★★★

    ── 为什么换这个思路（上一版踩的坑）────────────────────────────────
    上一版 `_detect_finger_peaks` 是**先找峰**：沿轮廓距离曲线找局部极大 ✗
    实测问题：**蜷起指节那种小凸起和噪声分不开** ✗
      平滑窗口大一点就把它抹掉、小一点就冒出一堆假峰 ✗
      扫遍参数最好也只有 21/40 能出正好 5 个峰 ✗

    ★★ 用户的洞察是对的，但正确的切入点是「谷」而不是「峰」★★
      · **指缝（谷）比指峰显著得多、也少得多** ✓ 4 条缝 vs 5 个峰 ✓
      · **4 条缝天然把轮廓切成 5 段** ✓ -> **段数固定为 5，永不落空** ✓
      · 顺序分配是**免费**的：段沿轮廓依次就是 T-I-M-R-P ✓

    ── 做法 ─────────────────────────────────────────────────────────
      ① 最大外轮廓，砍掉前臂切口那一段
      ② 沿轮廓算到掌心的距离 d（×R），平滑
      ③ 找所有局部极小（候选指缝）
      ④ **只取最深的 4 个**
      ⑤ 4 条缝把轮廓切成 5 段；每段的极值点 = 该手指的指峰
      ⑥ 按轮廓顺序返回 5 根手指（统一成"拇指在前"）

    返回 ``(fingers, webs)``：
      fingers  长度 5 的列表（按轮廓顺序），每项
               ``{"peak_point", "peak_dist", "protrusion", "angle_deg",
                  "seg_lo", "seg_hi", "peak_order"}``
      webs     长度 4 的列表，每项 ``{"point", "dist", "angle_deg"}``
    判不出来时返回 ``([], [])``
    """
    contours, _ = cv2.findContours(hand_mask, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_NONE)
    if not contours:
        return [], []
    cnt = max(contours, key=cv2.contourArea)
    pts = cnt.reshape(-1, 2).astype(np.float64)
    n = pts.shape[0]
    R = float(radius)
    if n < 48 or R <= 1e-6:
        return [], []
    center = np.asarray(palm_center, dtype=np.float64).reshape(2)
    delta = pts - center
    dist = np.linalg.norm(delta, axis=1) / R

    # ---- ① 砍掉前臂切口，把环形轮廓变成一条开链 ----
    u = np.asarray(up, dtype=np.float64).reshape(2)
    u = u / (float(np.linalg.norm(u)) + 1e-9)
    proj = delta @ u / R
    keep = proj > float(PEAK_CUT_PROJ)
    breaks = np.nonzero(~keep)[0]
    if breaks.size == 0:
        idx_line = np.arange(n)
    else:
        start = (int(breaks[0]) + 1) % n
        idx_line = (start + np.arange(n - int(breaks.size))) % n
    d_line = dist[idx_line]
    if d_line.size < 48:
        return [], []

    # ---- ② 平滑 ----
    win = max(3, int(round(float(PEAK_SMOOTH_WIN) * d_line.size)) | 1)
    d_s = _smooth_1d(d_line, win)
    m = int(d_s.size)

    # ---- ③ 找所有局部极小（候选指缝）+ 局部极大（用来算缝的深度）----
    span = max(2, int(round(float(PEAK_MIN_SEPARATION) * m)))
    cands = []
    peaks_all = []
    for i in range(1, m - 1):
        lo, hi = max(0, i - span), min(m, i + span + 1)
        seg = d_s[lo:hi]
        if d_s[i] <= seg.min() + 1e-9:
            cands.append(i)
        if d_s[i] >= seg.max() - 1e-9:
            peaks_all.append(i)
    cands = _thin_plateau(cands, d_s, want_max=False)
    peaks_all = _thin_plateau(peaks_all, d_s, want_max=True)
    if not peaks_all:
        peaks_all = [int(np.argmax(d_s))]
    if len(cands) < 4:
        return [], []

    # ---- ④ 只取最深的 4 条缝 ----
    scored = []
    for i in cands:
        left = [j for j in peaks_all if j < i]
        right = [j for j in peaks_all if j > i]
        hl = d_s[left[-1]] if left else d_s[0]
        hr = d_s[right[0]] if right else d_s[-1]
        scored.append((float(min(hl, hr) - d_s[i]), i))     # 深度
    scored.sort(key=lambda t: -t[0])
    webs_line = []
    min_gap = max(2, int(0.03 * m))
    for depth, i in scored:
        if depth < float(PEAK_WEB_MIN_DEPTH):
            continue
        if all(abs(i - j) >= min_gap for j in webs_line):
            webs_line.append(i)
        if len(webs_line) == 4:
            break
    if len(webs_line) != 4:
        return [], []
    webs_line.sort()

    # ---- ⑤ 4 条缝切成 5 段 ----
    bounds = [-1] + webs_line + [m]
    fingers, webs = [], []
    for i in webs_line:
        gi = int(idx_line[i])
        webs.append({"point": (float(pts[gi, 0]), float(pts[gi, 1])),
                     "dist": float(d_line[i]),
                     "angle_deg": float(np.degrees(np.arctan2(
                         float(delta[gi, 0]), -float(delta[gi, 1]))))})
    for k in range(5):
        lo, hi = bounds[k] + 1, bounds[k + 1]
        if hi - lo < 2:
            return [], []
        seg = d_line[lo:hi]
        p_local = lo + int(np.argmax(seg))
        gi = int(idx_line[p_local])
        base = []
        if k > 0:
            base.append(d_line[webs_line[k - 1]])
        if k < 4:
            base.append(d_line[webs_line[k]])
        b = max(base) if base else 0.0
        fingers.append({
            "peak_point": (float(pts[gi, 0]), float(pts[gi, 1])),
            "peak_dist": float(d_line[p_local]),
            "protrusion": float(d_line[p_local] - b),
            "angle_deg": float(np.degrees(np.arctan2(
                float(delta[gi, 0]), -float(delta[gi, 1])))),
            "seg_lo": int(lo), "seg_hi": int(hi), "peak_order": int(p_local),
        })

    # ---- ⑥ 统一成"拇指在前"的顺序 ----
    #   拇指的特征：角度最大（实测拇指 +46~+82，其余四根都在 +30 以下）
    if fingers[0]["angle_deg"] < fingers[-1]["angle_deg"]:
        fingers.reverse()
        webs.reverse()
    return fingers, webs


def _detect_finger_peaks(hand_mask: np.ndarray, palm_center, up, radius: float,
                         cut_point=None):
    """★★ 「指峰 + 指缝」：沿轮廓找每根手指的凸起和它们之间的凹谷 ★★

    ── 为什么要换这套（用户提出的方案，实测有效）────────────────────────
    现在那套（``_assign_finger_slots``）只检出**伸开的手指**的指尖 ✗
    蜷起的手指**根本不产生候选** ✗ 于是"5 个指尖怎么分配到 5 个位置"
    变成了一个**纯几何模板匹配** ✗ —— 而小指被透视缩短后就和无菌指分不开了 ✗

    ★ 但在标准照片里，**掩膜中 5 根手指全都看得见、而且不重叠** ✓
      那么沿轮廓走一圈，**每根手指都会形成一个凸起**：
        · 伸开的手指 -> 尖峰（指尖）
        · 蜷起的手指 -> 圆钝的凸起（指节）
      相邻两根之间必然有一个凹谷（指缝）✓

    ★★ 关键优势：每根手指都有自己的峰 -> 分配可以靠【轮廓顺序】★★
      而"手指从拇指到小指沿轮廓依次排列"是**解剖学固定、永不违反**的事实 ✓
      —— 这正是现在最大的错误来源（无名指↔小指混淆）的解药 ✓

    ── 做法 ──────────────────────────────────────────────────────────
      ① 取最大外轮廓，算每个点到掌心的距离 d（按 R 归一化）
      ② **砍掉前臂截断那条边**（那条直线不是手指形状，会造出两个假角）
      ③ 环形平滑 d
      ④ 找局部极大（峰）+ 局部极小（谷）
      ⑤ 过滤：峰必须比两侧谷明显凸出（否则是噪声）
      ⑥ 按**轮廓顺序**输出

    返回 ``(peaks, valleys)``，都是列表，元素是
    ``{"point": (x,y), "dist": d/R, "angle_deg": 相对掌轴的角, "index": 轮廓序号}``
    """
    contours, _ = cv2.findContours(hand_mask, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_NONE)
    if not contours:
        return [], []
    cnt = max(contours, key=cv2.contourArea)
    pts = cnt.reshape(-1, 2).astype(np.float64)
    n = pts.shape[0]
    if n < 32:
        return [], []
    center = np.asarray(palm_center, dtype=np.float64).reshape(2)
    R = float(radius)
    if R <= 1e-6:
        return [], []

    delta = pts - center
    dist = np.linalg.norm(delta, axis=1) / R

    # ② 砍掉前臂截断边：用"沿掌轴 up 方向的投影"判断
    #    截断发生在掌心【背后】（-up 方向），所以投影值小的那些点属于切口
    u = np.asarray(up, dtype=np.float64).reshape(2)
    u = u / (float(np.linalg.norm(u)) + 1e-9)
    proj = delta @ u / R                       # 沿掌轴归一化坐标（+ = 指向手指）
    keep = proj > float(PEAK_CUT_PROJ)         # 只留"手指那半边"的轮廓
    if int(np.count_nonzero(keep)) < 24:
        keep = np.ones(n, dtype=bool)

    # 用"保留区的两端"把环形轮廓切成一条开链
    idx_keep = np.nonzero(keep)[0]
    # 找最长的连续段（环形的）
    breaks = np.nonzero(~keep)[0]
    if breaks.size == 0:
        order = np.arange(n)
    else:
        # 从第一个被砍掉的点之后开始，绕过一圈，到最后一个被砍掉的点结束
        start = (int(breaks[0]) + 1) % n
        length = n - int(breaks.size)
        order = (start + np.arange(length)) % n
    d_line = dist[order]
    if d_line.size < 24:
        return [], []

    # ③ 平滑（一维，边界用边缘复制）
    win = max(3, int(round(float(PEAK_SMOOTH_WIN) * d_line.size)) | 1)
    d_s = _smooth_1d(d_line, win)

    # ④ 找局部极大 / 极小（在开链上找，端点不算）
    span = max(2, int(round(float(PEAK_MIN_SEPARATION) * d_line.size)))
    peaks_i, valleys_i = [], []
    for i in range(1, d_line.size - 1):
        lo = max(0, i - span)
        hi = min(d_line.size, i + span + 1)
        seg = d_s[lo:hi]
        if d_s[i] >= seg.max() - 1e-9:
            peaks_i.append(i)
        if d_s[i] <= seg.min() + 1e-9:
            valleys_i.append(i)
    # 同一个平台只留一个（取最极端的）
    peaks_i = _thin_plateau(peaks_i, d_s, want_max=True)
    valleys_i = _thin_plateau(valleys_i, d_s, want_max=False)

    # ⑤ 过滤：峰必须比两侧最近的谷明显高
    def _pack(i, is_peak):
        gi = int(order[i])
        p = pts[gi]
        ang = float(np.degrees(np.arctan2(float(delta[gi, 0]), -float(delta[gi, 1]))))
        return {"point": (float(p[0]), float(p[1])), "dist": float(d_line[i]),
                "angle_deg": ang, "index": gi, "order": int(i), "peak": bool(is_peak)}

    peaks, valleys = [], []
    for i in peaks_i:
        left = [j for j in valleys_i if j < i]
        right = [j for j in valleys_i if j > i]
        base = []
        if left:
            base.append(d_s[left[-1]])
        if right:
            base.append(d_s[right[0]])
        if not base:
            continue
        if d_line[i] - max(base) < float(PEAK_MIN_PROMINENCE):
            continue                                # 凸得不够 -> 不是手指
        peaks.append(_pack(i, True))
    for i in valleys_i:
        valleys.append(_pack(i, False))
    return peaks, valleys


def _smooth_1d(a: np.ndarray, win: int) -> np.ndarray:
    """一维滑动平均（边缘复制）。``win`` 应当是奇数。"""
    win = max(1, int(win) | 1)
    if win <= 1 or a.size < win:
        return a.astype(np.float64)
    pad = win // 2
    ext = np.concatenate([np.full(pad, a[0]), a.astype(np.float64), np.full(pad, a[-1])])
    ker = np.ones(win, dtype=np.float64) / float(win)
    return np.convolve(ext, ker, mode="valid")


def _thin_plateau(idx_list, values, want_max: bool):
    """把"平台"式的极值点压成一个（相邻序号只留最极端那个）。"""
    if not idx_list:
        return []
    out = [idx_list[0]]
    for i in idx_list[1:]:
        if i - out[-1] <= 1:                        # 紧挨着 -> 同一平台
            if want_max:
                if values[i] > values[out[-1]]:
                    out[-1] = i
            else:
                if values[i] < values[out[-1]]:
                    out[-1] = i
        else:
            out.append(i)
    return out


def _assign_finger_slots(tip_angles, tip_lengths=None, web_xs=None):
    """Match observed tips to slots, preserving anatomical order.

    Every (slot subset, angular spread, rotation) must be scored INSIDE
    all three loops. Return each subset's best fit for diagnosis. The cost
    margin is a score difference, not a calibrated probability.

    Existing weights and priors are retained for a controlled bug fix.
    In particular, free rotation can still make adjacent identities ambiguous.
    """
    template = np.asarray(FINGER_TEMPLATE_DEG, dtype=np.float64)
    order = sorted(range(len(tip_angles)), key=lambda j: -float(tip_angles[j]))
    ta = [float(tip_angles[j]) for j in order]
    count = len(ta)
    lens = [None] * count
    if tip_lengths is not None:
        for pos, j in enumerate(order):
            try:
                lens[pos] = float(tip_lengths[j])
            except (TypeError, ValueError, IndexError):
                pass
    lo, hi = map(float, FINGER_THUMB_RANGE_DEG)
    has_thumb = bool(count and lo < ta[0] < hi)
    anchor = "thumb" if has_thumb else "palm_axis"
    candidates = []
    for mask in range(32):
        combo = tuple(i for i in range(5) if (mask >> i) & 1)
        if len(combo) != count:
            continue
        if has_thumb and 0 not in combo:
            continue
        if not has_thumb and count < 5 and 0 in combo:
            continue
        candidates.append(combo)
    shifts = [None] if has_thumb else list(np.arange(
        -float(FINGER_NONTHUMB_SHIFT_DEG), float(FINGER_NONTHUMB_SHIFT_DEG) + 1e-9,
        float(FINGER_NONTHUMB_SHIFT_STEP)))
    # No observed tip carries rotation information.
    if count == 0:
        shifts = [0.0]
    obs_webs = sorted([float(v) for v in (web_xs or [])], reverse=True)
    ranked = []
    best = None
    for combo in candidates:
        exp_webs = _nominal_boundaries(combo)
        web_sse = float(FINGER_WEB_COUNT_PENALTY) if len(obs_webs) != len(exp_webs) else 0.0
        web_sse += sum((o - e) ** 2 for o, e in zip(obs_webs, exp_webs))
        non_thumb = [i for i in combo if i != 0]
        penalty = (float(FINGER_CONTIGUOUS_PENALTY)
                   if not has_thumb and non_thumb and
                   non_thumb != list(range(1, 1 + len(non_thumb))) else 0.0)
        combo_best = None
        for scale in map(float, FINGER_SEARCH_SCALES):
            len_sse = sum((ln - scale * float(FINGER_TEMPLATE_LEN[slot])) ** 2
                          for slot, ln in zip(combo, lens) if ln is not None)
            for shift in shifts:
                delta = ta[0] - scale * float(template[0]) if shift is None else float(shift)
                predicted = [delta + scale * float(template[i]) for i in combo]
                sse = float(sum((a - p) ** 2 for a, p in zip(ta, predicted)))
                costs = {
                    "angle": float(FINGER_W_ANGLE) * sse,
                    "length": float(FINGER_W_LEN) * len_sse,
                    "web": float(FINGER_W_WEB) * web_sse,
                    "scale": float(FINGER_W_SCALE) * (scale - 1.0) ** 2,
                    "contiguity": penalty,
                }
                total = sum(costs.values())
                detail = {"delta_deg": delta, "sse": sse, "len_sse": len_sse,
                          "web_sse": web_sse, "penalty": penalty, "anchor": anchor,
                          "slots": list(combo), "scale": scale, "total": total,
                          "costs": costs, "predicted_angles_deg": predicted,
                          "observed_web_x": obs_webs, "expected_web_x": exp_webs}
                if combo_best is None or total < combo_best["total"] - 1e-9:
                    combo_best = detail
                if best is None or total < best["total"] - 1e-9:
                    best = detail
        if combo_best is not None:
            ranked.append(combo_best)
    if best is None:
        return [False] * 5, order, anchor, {
            "delta_deg": 0.0, "sse": None, "valid_assignment": False, "candidates": []}
    ranked.sort(key=lambda item: item["total"])
    detail = dict(best)
    detail["valid_assignment"] = True
    detail["candidates"] = ranked
    detail["score_margin"] = ranked[1]["total"] - ranked[0]["total"] if len(ranked) > 1 else None
    states = [i in best["slots"] for i in range(5)]
    return states, order, anchor, detail


def _match_finger_template(angles: np.ndarray, profile: np.ndarray):
    """★ 用"名义角度模板 + 允许整体旋转/缩放 + 穷举子集"匹配径向剖面。

    返回 ``(states, ext_at_template, detail)``：

        states          5 个 bool，顺序 = (拇指, 食指, 中指, 无名指, 小指)
        ext_at_template 5 个 float，在**匹配到的角度**上量到的延伸长度（× R）
        detail          dict，含匹配到的旋转/缩放/得分，调试用

    **为什么这样比固定扇区稳**：掌轴估计偏 15~30° 时，固定扇区整片错位；
    这里旋转量 δ 是**搜出来的**，把误差整个吸收掉。张开程度的变化由缩放 s 吸收。
    子集穷举（2^5=32）则天然处理"漏检/多检"。
    """
    angles = np.asarray(angles, dtype=np.float64)
    profile = np.asarray(profile, dtype=np.float64)
    template = np.asarray(FINGER_TEMPLATE_DEG, dtype=np.float64)

    shifts = np.arange(-float(FINGER_SEARCH_SHIFT_DEG),
                       float(FINGER_SEARCH_SHIFT_DEG) + 1e-9,
                       float(FINGER_SEARCH_SHIFT_STEP), dtype=np.float64)
    scales = np.asarray(FINGER_SEARCH_SCALES, dtype=np.float64)

    # 所有 (scale, shift) 组合 -> 预测角度矩阵 (N, 5)
    ss, dd = np.meshgrid(scales, shifts, indexing="ij")
    pred = (dd.ravel()[:, None] + ss.ravel()[:, None] * template[None, :])

    # 在剖面上插值（越界取 0 = 那里没有掩膜）
    vals = np.empty_like(pred)
    for i in range(5):
        vals[:, i] = np.interp(pred[:, i], angles, profile, left=0.0, right=0.0)

    # 代价：每根手指到"伸开中心"/"蜷起中心"的距离
    cost_ext = np.abs(vals - float(FINGER_EXT_CENTER))
    cost_curled = np.abs(vals - float(FINGER_CURLED_CENTER))

    # 32 个子集的得分 = -( Σ_{i∈S} cost_ext_i + Σ_{i∉S} cost_curled_i )
    #   ★ 展开： = -Σ_all cost_curled - Σ_{i∈S}(cost_ext_i - cost_curled_i)
    #   ⚠️ 所以 delta 那一项前面是**减号**！写成加号会让"包含手指"反而加分，
    #      结果永远选"5 根全伸开"（我第一次就栽在这，28 张全判 TIMRP）。
    bits = np.array([[(m >> i) & 1 for i in range(5)] for m in range(32)],
                    dtype=np.float64)                                   # (32, 5)
    base = -cost_curled.sum(axis=1)                                     # (N,)
    delta = cost_ext - cost_curled                                      # (N, 5)
    scores = base[:, None] - delta @ bits.T                             # (N, 32)

    flat = int(np.argmax(scores))
    n_idx, m = divmod(flat, 32)
    states = [bool((m >> i) & 1) for i in range(5)]
    matched_scale = float(scales[n_idx // len(shifts)])
    matched_shift = float(shifts[n_idx % len(shifts)])
    detail = {
        "subset": m,
        "shift_deg": matched_shift,
        "scale": matched_scale,
        "score": float(scores[n_idx, m]),
        "angles_used": [float(matched_shift + matched_scale * a) for a in template],
    }
    return states, [float(v) for v in vals[n_idx]], detail


def _finger_states(mask: np.ndarray, palm_center, up, radius: float, tips, web_gaps=None,
                   contour=None):
    """Return five states and diagnostic measurements.

    Geometry mode projects local finger axes onto a transverse palm reference
    line to assign identity. Local width and aspect determine extension, so a
    detected candidate can be assigned to a curled finger. This reference-line
    intersection is a positioning feature, not an anatomical joint estimate.

    If geometric measurements are unavailable, retain the legacy angle method
    and record its fallback reason. Neither method reads image labels.
    The extension diagnostics mean local branch length in geometry mode and
    radial reach in legacy mode. Rendering distinguishes these two meanings.
    """
    geometry_failure = None
    if FINGER_IDENTITY_MODE == "geometry":
        if contour is None:
            contours, _ = cv2.findContours(mask, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_NONE)
            contour = max(contours, key=cv2.contourArea) if contours else None
        measured, geometry_failure = FG.recognize_fingers(
            mask, contour, palm_center, up, radius, tips or [])
        if measured is not None:
            extensions = [0.0] * 5
            angles_used = [0.0] * 5
            for feature in measured["features"]:
                slot = feature["slot"]
                extensions[slot] = feature["length_r"]
                x, y = feature["tip_local"]
                angles_used[slot] = float(np.degrees(np.arctan2(x, -y)))
            measured["anchor"] = "local_finger_axis"
            return measured["states"], extensions, angles_used, measured, [0.0] * 5
    elif FINGER_IDENTITY_MODE != "legacy":
        raise ValueError("Unknown finger identity mode: %s" % FINGER_IDENTITY_MODE)

    tip_angles = []
    tip_lengths = []
    for t in (tips or []):
        x = float(t["local"][0])
        y = float(t["local"][1])
        tip_angles.append(float(np.degrees(np.arctan2(x, -y))))
        tip_lengths.append(float(np.hypot(x, y)))     # 指尖到掌心的距离，已经是 R 的倍数

    # 指缝的横向位置（单位 R），按从拇指侧到小指侧排序
    web_xs = sorted([float(g["local"][0]) for g in (web_gaps or [])], reverse=True)

    # ★★ 手性（掌心 / 手背朝镜头）用**两个假设比代价**来定，不写死门槛 ★★
    #   解剖学上，右手掌心朝镜头时拇指在 right 侧；手背朝镜头时左右相反。
    #   与其去写"缝的 x 小于 −0.3 就镜像"这种魔法数字，不如把两种手性**各跑一遍分配**，
    #   取总代价更低的那个 —— 用同一套代价函数做模型选择，不需要任何新阈值 ✓
    #   （实测 gesture_33 三张就是手背朝镜头，正面假设下怎么配都别扭，镜像假设自然胜出）
    states, _order, anchor, detail = _assign_finger_slots(tip_angles, tip_lengths, web_xs)
    best_total = float(detail.get("total", float("inf")))
    mirrored = False
    if FINGER_TEST_MIRROR:
        st_m, _o_m, _a_m, det_m = _assign_finger_slots(
            [-a for a in tip_angles], tip_lengths, [-v for v in web_xs])
        if float(det_m.get("total", float("inf"))) < best_total - 1e-6:
            states, anchor, detail, mirrored = st_m, _a_m, det_m, True
            best_total = float(det_m.get("total", float("inf")))
    detail["mirrored"] = mirrored

    angles, profile = _radial_profile(mask, palm_center, up, radius)
    delta = float(detail.get("delta_deg", 0.0))
    scale_fit = float(detail.get("scale", 1.0))
    used = [delta + scale_fit * float(FINGER_TEMPLATE_DEG[i]) for i in range(5)]
    if mirrored:
        used = [-a for a in used]
    extensions = [float(np.interp(a, angles, profile)) for a in used]
    # ★ 每根手指"按模板应该伸到多远"（× R）—— 画调试标记用：
    #   和上面的 extensions（沿射线**实测**到哪）一比，就能看出哪根对不上
    expected = [float(FINGER_TEMPLATE_LEN[i]) * scale_fit for i in range(5)]

    # 拇指兜底：本次没用拇指锚（说明没检出拇指指尖），但剖面上拇指方向明显很长
    if anchor != "thumb" and not states[0]:
        if extensions[0] >= float(FINGER_EXTENDED_MIN_R):
            states[0] = True
            detail["thumb_from_profile"] = True
    detail["anchor"] = anchor
    detail["tip_angles_deg"] = [round(a, 1) for a in tip_angles]
    detail["expect_len"] = [round(v, 2) for v in expected]
    detail["method"] = "angle_template_legacy"
    if geometry_failure is not None:
        detail["geometry_fallback_reason"] = geometry_failure
    return states, extensions, used, detail, expected


