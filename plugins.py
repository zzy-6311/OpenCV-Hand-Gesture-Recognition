_CJK_FONT_CACHE: dict = {}


def _load_cjk_font(size: int):
    """按需加载中文字体。找不到就返回 None（调用方必须能接受 None）。"""
    if size in _CJK_FONT_CACHE:
        return _CJK_FONT_CACHE[size]
    font = None
    try:
        from PIL import ImageFont
    except Exception:
        ImageFont = None
    if ImageFont is not None:
        for path in CJK_FONT_CANDIDATES:
            if os.path.exists(path):
                try:
                    font = ImageFont.truetype(path, int(size))
                    break
                except Exception:
                    font = None
    _CJK_FONT_CACHE[size] = font
    return font


def text_width(text: str, size: int) -> int:
    """量一段文字有多宽（像素）。面板尺寸和右对齐都靠它算准。"""
    font = _load_cjk_font(size)
    if font is not None:
        try:
            return int(font.getlength(text))
        except Exception:
            pass
    return int(len(text) * size * 0.62)      # 没有字体时的兜底估算


def _put_text_outlined(image, text, origin, scale=0.7, color=COLOR_LABEL, thickness=2):
    """带黑描边的**英文/数字**文字（cv2 版，快）。

    ⚠️ 只能画 ASCII。要画中文请用 draw_text_lines()。
    """
    cv2.putText(image, text, origin, cv2.FONT_HERSHEY_SIMPLEX, scale,
                COLOR_OUTLINE, thickness + 3, cv2.LINE_AA)
    cv2.putText(image, text, origin, cv2.FONT_HERSHEY_SIMPLEX, scale,
                color, thickness, cv2.LINE_AA)


def draw_panel(image: np.ndarray, box, alpha: float = None,
               border=None) -> None:
    """画一块半透明深色面板，给 HUD 文字当底衬（否则白底/花背景上字看不清）。"""
    x0, y0, x1, y1 = (int(v) for v in box)
    x0 = max(0, x0); y0 = max(0, y0)
    x1 = min(image.shape[1], x1); y1 = min(image.shape[0], y1)
    if x1 - x0 < 2 or y1 - y0 < 2:
        return
    region = image[y0:y1, x0:x1]
    dark = np.full_like(region, 16)
    cv2.addWeighted(region, 1.0 - (HUD_PANEL_ALPHA if alpha is None else alpha),
                    dark, (HUD_PANEL_ALPHA if alpha is None else alpha),
                    0.0, dst=region)
    cv2.rectangle(image, (x0, y0), (x1 - 1, y1 - 1),
                  HUD_PANEL_BORDER if border is None else border, 1)


def draw_text_lines(image: np.ndarray, lines, origin, panel: bool = False) -> int:
    """画多行文字，**支持中文**。返回整块画完后底部的 y 坐标。

    lines: [(文字, 字号px, BGR颜色), ...]；origin 是第一行的左上角。
    panel: True = 先在文字底下铺一块半透明面板再写字。

    ★ 什么时候该用 panel：
      小字号的中文笔画很密，**8 方向黑描边会把字内空隙填满，糊成一团黑块**。
      这种情况用"底衬面板 + 不描边"才清楚（ROI 里那几行就是这么处理的）。
      大字号（>=22px）可以不用面板，靠描边就够。

    ★ 性能：整块只做一次 PIL 往返，而且**只转换文字覆盖的那一小块区域**。
      如果对整幅 1920x1440 反复做 BGR<->RGB 转换，每行都要好几毫秒，
      一屏七八行就吃掉几十毫秒 —— 视频流下这是不能接受的。
    """
    lines = [ln for ln in lines if ln and str(ln[0])]
    if not lines:
        return int(origin[1])

    x0, y0 = int(origin[0]), int(origin[1])
    sizes = [int(ln[1]) for ln in lines]
    block_w = max(text_width(str(ln[0]), int(ln[1])) for ln in lines) + 10
    block_h = sum(sizes) + HUD_LINE_GAP * (len(lines) - 1) + 10

    bx0 = max(0, x0 - 4)
    by0 = max(0, y0 - 4)
    bx1 = min(image.shape[1], x0 + block_w + 4)
    by1 = min(image.shape[0], y0 + block_h + 4)
    if bx1 - bx0 < 2 or by1 - by0 < 2:
        return y0 + block_h

    use_pil = True
    try:
        from PIL import Image, ImageDraw
    except Exception:
        use_pil = False
    if use_pil and any(_load_cjk_font(s) is None for s in sizes):
        use_pil = False

    # 底衬要在转换之前铺在**原图**上，这样文字区域才干净
    if panel:
        draw_panel(image, (bx0, by0, bx1, by1), alpha=0.68)

    if use_pil:
        sub = image[by0:by1, bx0:bx1]
        pil = Image.fromarray(cv2.cvtColor(sub, cv2.COLOR_BGR2RGB))
        painter = ImageDraw.Draw(pil)
        cursor = y0 - by0
        for text, size, color in lines:
            font = _load_cjk_font(int(size))
            px, py = x0 - bx0, cursor
            rgb = (int(color[2]), int(color[1]), int(color[0]))
            if not panel:                       # 有底衬就不用描边（描边会糊）
                for dx, dy in ((1, 0), (0, 1), (1, 1)):     # 只往右下描，最省最清楚
                    painter.text((px + dx, py + dy), str(text), font=font, fill=(0, 0, 0))
            painter.text((px, py), str(text), font=font, fill=rgb)
            cursor += int(size) + HUD_LINE_GAP
        image[by0:by1, bx0:bx1] = cv2.cvtColor(np.asarray(pil), cv2.COLOR_RGB2BGR)
        return y0 + block_h

    # 退回 cv2：画不了中文，把非 ASCII 换掉，至少不显示乱码
    cursor = y0
    for text, size, color in lines:
        safe = str(text).encode("ascii", "replace").decode("ascii")
        scale = max(0.4, int(size) / 30.0)
        if not panel:
            cv2.putText(image, safe, (x0, cursor + int(size)),
                        cv2.FONT_HERSHEY_SIMPLEX, scale, COLOR_OUTLINE, 3, cv2.LINE_AA)
        cv2.putText(image, safe, (x0, cursor + int(size)),
                    cv2.FONT_HERSHEY_SIMPLEX, scale, color, 1, cv2.LINE_AA)
        cursor += int(size) + HUD_LINE_GAP
    return y0 + block_h


def draw_info_panel(image: np.ndarray, lines, anchor: str = "top-left") -> None:
    """把一组 (文字,字号,颜色) 行画成一块带底衬的面板。

    anchor: "top-left" 贴左上角，"top-right" 贴右上角（自动右对齐）。
    会自动按画面尺寸限制面板宽度，避免和别处的文字叠在一起。
    """
    lines = [ln for ln in lines if ln and str(ln[0])]
    if not lines:
        return
    height, width = image.shape[:2]
    sizes = [int(ln[1]) for ln in lines]
    natural_w = max(text_width(str(ln[0]), int(ln[1])) for ln in lines)
    max_w = int(width * HUD_MAX_WIDTH_RATIO)
    panel_w = min(natural_w, max_w) + HUD_TEXT_PAD_X * 2
    panel_h = sum(sizes) + HUD_LINE_GAP * (len(lines) - 1) + HUD_TEXT_PAD_Y * 2

    if anchor == "top-right":
        x1 = width - HUD_MARGIN
        x0 = max(HUD_MARGIN, x1 - panel_w)
    else:
        x0 = HUD_MARGIN
        x1 = min(width - HUD_MARGIN, x0 + panel_w)
    y0 = HUD_MARGIN
    y1 = min(height - HUD_MARGIN, y0 + panel_h)
    draw_panel(image, (x0, y0, x1, y1))

    text_x = x0 + HUD_TEXT_PAD_X
    if anchor == "top-right":                      # 右对齐
        text_x = max(x0 + 4, x1 - HUD_TEXT_PAD_X - natural_w)
    draw_text_lines(image, lines, (text_x, y0 + HUD_TEXT_PAD_Y))


# --- ★ 手指状态方块（主输出）的显示参数 -------------------------------------
#  5 个正方形横排，顺序 = (拇指, 食指, 中指, 无名指, 小指)
#  **实心 = 这根手指伸开；空心 = 蜷起**
FINGER_BOX_SIZE = 54              # 方块边长（像素，画在帧上、缩放前）
FINGER_BOX_GAP = 12               # 方块间距
FINGER_BOX_THICKNESS = 4          # 空心方块的线宽
COLOR_FINGER_ON = (0, 220, 0)     # 实心（伸开）：亮绿
COLOR_FINGER_OFF = (120, 120, 120)  # 空心（蜷起）：灰
FINGER_BOX_TAGS = ("T", "I", "M", "R", "P")   # 方块下方标记（拇指/食指/中指/无名指/小指）
COLOR_UNSETTLED = (0, 215, 255)   # ★ 手在动（过渡帧）时的提示色：橙黄

# --- ★★ 每根手指的「位置标志」（检查问题用）★★ ------------------------------
# 打开后在画面上给 5 根手指各画一条射线 + 两个标记：
#   · 空心黄圈 = 按模板**预期**指尖应该在哪
#   · 实心点   = 沿射线**实测**延伸到哪里（伸开=绿，蜷起=灰）
# 两者对不上 -> 就是那根手指判错的地方 ✓
# 想关掉（画面太乱时）改成 False 即可。
FINGER_DEBUG_DRAW = True
FINGER_DEBUG_RAY_LEN_R = 3.6      # 射线画多长（× R）


def _draw_dashed_rect(img, p1, p2, color, dash=14, thickness=3) -> None:
    """画一个虚线矩形（用短线段拼）。用来表示"这一帧不算数"。"""
    x1, y1 = int(p1[0]), int(p1[1])
    x2, y2 = int(p2[0]), int(p2[1])
    d = max(2, int(dash))
    for x in range(x1, x2, d * 2):
        cv2.line(img, (x, y1), (min(x + d, x2), y1), color, thickness)
        cv2.line(img, (x, y2), (min(x + d, x2), y2), color, thickness)
    for y in range(y1, y2, d * 2):
        cv2.line(img, (x1, y), (x1, min(y + d, y2)), color, thickness)
        cv2.line(img, (x2, y), (x2, min(y + d, y2)), color, thickness)


def _draw_recognition(base: np.ndarray, result: Optional[dict]) -> np.ndarray:
    """把识别结果画到给定底图上。"""
    height, width = base.shape[:2]
    if result is None:
        _put_text_outlined(base, "no hand", (20, 40), 0.9, (0, 0, 255), 2)
        return base

    palm_center = result["palm_center"]
    radius = result["palm_radius"]
    up = result["up"]
    wrist = result["wrist"]
    center_px = (int(round(palm_center[0])), int(round(palm_center[1])))

    # 凸包（细线）：实心度 = 轮廓面积 / 凸包面积，把它画出来你就能看到
    # "手指之间的凹陷"是怎么让实心度变小的。先画，后面的标注盖在上面。
    hull = result.get("hull")
    if hull is not None and len(hull) >= 3:
        cv2.drawContours(base, [hull], -1, (255, 255, 0), 1, cv2.LINE_AA)

    # 掌心 + 手掌尺度圆
    cv2.circle(base, center_px, int(round(radius)), COLOR_PALM, 2)
    cv2.drawMarker(base, center_px, COLOR_PALM, cv2.MARKER_CROSS, 40, 3)

    # 掌轴（指向手指方向）和它的垂直方向
    axis_length = radius * 1.4
    tip_up = (int(round(palm_center[0] + up[0] * axis_length)),
              int(round(palm_center[1] + up[1] * axis_length)))
    cv2.arrowedLine(base, center_px, tip_up, COLOR_WRIST, 2, tipLength=0.15)
    right = np.array([-up[1], up[0]])
    tip_right = (int(round(palm_center[0] + right[0] * radius * 0.7)),
                 int(round(palm_center[1] + right[1] * radius * 0.7)))
    cv2.arrowedLine(base, center_px, tip_right, COLOR_WRIST, 2, tipLength=0.15)

    # 手腕 + 截断线
    if wrist is not None:
        wrist_px = (int(round(wrist[0])), int(round(wrist[1])))
        cv2.circle(base, wrist_px, 6, COLOR_WRIST, -1)
        cv2.line(base, wrist_px, center_px, COLOR_WRIST, 1)
    # 截断线：位置按 RECOG_TRUNCATE_FACTOR（是真的切在那），
    # 长度用 RECOG_TRUNCATE_LINE_HALF（只是画出来给你看），并夹在画面内。
    truncate_point = palm_center - up * (float(RECOG_TRUNCATE_FACTOR) * radius)
    half = float(RECOG_TRUNCATE_LINE_HALF) * radius
    raw1 = truncate_point + right * half
    raw2 = truncate_point - right * half
    p1 = (int(np.clip(round(raw1[0]), 0, width - 1)),
          int(np.clip(round(raw1[1]), 0, height - 1)))
    p2 = (int(np.clip(round(raw2[0]), 0, width - 1)),
          int(np.clip(round(raw2[1]), 0, height - 1)))
    cv2.line(base, p1, p2, (128, 128, 128), 2)

    # 指缝
    for gap in result["gaps"]:
        point = (int(round(gap["point"][0])), int(round(gap["point"][1])))
        cv2.circle(base, point, 10, COLOR_GAP, 2)

    # =======================================================================
    # ★★ 每根手指的「位置标志」（检查问题用）★★
    #   对 5 根手指各画一条射线，并标三样东西：
    #     · 射线本身      —— 算法认为这根手指在**哪个方向**（用分配好的角度）
    #     · 空心圈(黄)    —— 按模板**预期**指尖应该在哪（×R，含拟合出的缩放）
    #     · 实心点(绿/灰) —— 沿射线**实测**延伸到哪里（伸开=绿，蜷起=灰）
    #   预期圈和实测点对不上 -> 就是那根手指判错的地方 ✓
    #   ⚠️ 只在 FINGER_DEBUG_DRAW 打开时画，免得平时画面太乱
    geometry_match = result.get("finger_match") or {}
    using_geometry = geometry_match.get("method") == "root_geometry_q10"
    if FINGER_DEBUG_DRAW and using_geometry:
        # Measured tip -> projected root, labeled by anatomical identity.
        # Do not display unfitted template rays as if they were observations.
        for feature in geometry_match.get("features", []):
            slot = feature["slot"]
            tip_px = tuple(int(round(v)) for v in feature["point"])
            root = feature.get("root_point") or feature["base_point"]
            root_px = tuple(int(round(v)) for v in root)
            col = COLOR_FINGER_ON if feature["extended"] else COLOR_FINGER_OFF
            cv2.line(base, root_px, tip_px, col, 3, cv2.LINE_AA)
            cv2.circle(base, root_px, 7, (0, 255, 255), 2, cv2.LINE_AA)
            cv2.circle(base, tip_px, 7, col, -1, cv2.LINE_AA)
            text = "%s %s" % (FINGER_BOX_TAGS[slot], "ON" if feature["extended"] else "OFF")
            _put_text_outlined(base, text, (tip_px[0] + 12, tip_px[1] - 12), .7, col, 2)
    elif FINGER_DEBUG_DRAW:
        up_v = np.asarray(up, dtype=np.float64).reshape(2)
        right_v = np.array([-up_v[1], up_v[0]])
        ray_c = float(radius)
        ray_len = float(FINGER_DEBUG_RAY_LEN_R) * ray_c
        angles = result.get("finger_ray_angles") or []
        exts = result.get("finger_extensions") or []
        exps = result.get("finger_expect_len") or []
        sts = result.get("finger_states") or []
        for i in range(min(5, len(angles))):
            a = float(angles[i])
            # 角度约定：θ 从掌轴(up)量起，正方向 = right（拇指侧）
            d = np.array([np.sin(np.radians(a)), -np.cos(np.radians(a))], dtype=np.float64)
            # 转到图像坐标：把局部 (x沿right, y沿up) 换成像素方向
            dirv = right_v * d[0] + up_v * (-d[1])
            n = float(np.linalg.norm(dirv))
            if n < 1e-9:
                continue
            dirv = dirv / n
            col = COLOR_FINGER_ON if (i < len(sts) and sts[i]) else COLOR_FINGER_OFF
            p_ray = (int(round(palm_center[0] + dirv[0] * ray_len)),
                     int(round(palm_center[1] + dirv[1] * ray_len)))
            cv2.line(base, center_px, p_ray, col, 1, cv2.LINE_AA)
            if i < len(exps):
                e = float(exps[i])
                pe = (int(round(palm_center[0] + dirv[0] * e * ray_c)),
                      int(round(palm_center[1] + dirv[1] * e * ray_c)))
                cv2.circle(base, pe, 13, (0, 255, 255), 2, cv2.LINE_AA)   # 预期位置
            if i < len(exts):
                m = float(exts[i])
                pm = (int(round(palm_center[0] + dirv[0] * m * ray_c)),
                      int(round(palm_center[1] + dirv[1] * m * ray_c)))
                cv2.circle(base, pm, 7, col, -1, cv2.LINE_AA)              # 实测位置
            if i < len(exps) and i < len(exts):
                pe = (int(round(palm_center[0] + dirv[0] * float(exps[i]) * ray_c)),
                      int(round(palm_center[1] + dirv[1] * float(exps[i]) * ray_c)))
                pm = (int(round(palm_center[0] + dirv[0] * float(exts[i]) * ray_c)),
                      int(round(palm_center[1] + dirv[1] * float(exts[i]) * ray_c)))
                cv2.line(base, pe, pm, (0, 255, 255), 1, cv2.LINE_AA)
            # 标签：字母 + 实测/预期
            lab_at = (int(round(palm_center[0] + dirv[0] * (ray_len + 26))),
                      int(round(palm_center[1] + dirv[1] * (ray_len + 26))))
            txt = "%s" % FINGER_BOX_TAGS[i]
            if i < len(exts) and i < len(exps):
                txt += " %.1f/%.1f" % (float(exts[i]), float(exps[i]))
            _put_text_outlined(base, txt, lab_at, 0.7, col, 2)

    # 每根手指：指根 -> 指尖 一条线 + 两端点 + 编号和长度
    for finger in ([] if using_geometry else result["fingers"]):
        tip_px = (int(round(finger["tip"][0])), int(round(finger["tip"][1])))
        base_px = (int(round(finger["base"][0])), int(round(finger["base"][1])))
        cv2.line(base, base_px, tip_px, COLOR_TIP, 3)
        cv2.circle(base, base_px, 7, COLOR_BASE, -1)
        cv2.circle(base, tip_px, 9, COLOR_TIP, -1)
        cv2.circle(base, tip_px, 11, (255, 255, 255), 2)
        _put_text_outlined(base, str(finger["index"]),
                           (tip_px[0] + 14, tip_px[1] - 10), 0.8, COLOR_TIP, 2)
        mid = ((tip_px[0] + base_px[0]) // 2, (tip_px[1] + base_px[1]) // 2)
        _put_text_outlined(base, "%.2fR" % finger["length_ratio"],
                           (mid[0] + 12, mid[1]), 0.55, COLOR_LABEL, 1)

    # =======================================================================
    # HUD：左上角一块面板，装"分类结果 + 统计"
    #   ★ 中文必须走 draw_text_lines（PIL 渲染）—— cv2.putText 画中文是乱码。
    #   ★ 面板宽度自适应并按画面比例设上限，避免和别处的文字叠在一起。
    # =======================================================================
    # ---- ★★ 主输出：5 个正方形（实心 = 伸开，空心 = 蜷起）★★ ----
    #   顺序 = FINGER_NAMES = (拇指, 食指, 中指, 无名指, 小指)
    #   ⚠️ 这里原来是显示 "GESTURE 3" 之类的**数字手势标签**，那一套已按用户要求
    #      整套删除（classify_gesture 也删了）—— 机械手要控制的是**具体哪几根手指**。
    states = list(result.get("finger_states") or [])
    extensions = list(result.get("finger_extensions") or [])
    while len(states) < 5:
        states.append(False)
    while len(extensions) < 5:
        extensions.append(0.0)

    box = int(FINGER_BOX_SIZE)
    gap = int(FINGER_BOX_GAP)
    bx0 = int(HUD_MARGIN)
    by0 = int(HUD_MARGIN)
    # ★ 这一帧手稳不稳（由 stability_gate 写进结果里）
    #   settled=False 时，下面画的 states 其实是"上次稳定时的判定"（保持值），
    #   所以方块整体套一个黄虚线框 + 文字里说明，避免误以为它是本帧判的。
    settled = bool(result.get("settled", True))
    # ⚠️⚠️ **显示顺序：拇指在最右** ⚠️⚠️
    #   右手掌心朝镜头时，拇指就在**画面右侧** —— 方块要跟画面一致，
    #   所以从左到右 = 小指, 无名指, 中指, 食指, 拇指。
    #   （内部下标 i 仍是 FINGER_NAMES 的顺序：0=拇指 … 4=小指，只在**画**的时候反过来。）
    for pos in range(5):
        i = 4 - pos                       # pos=0 -> i=4 小指 …… pos=4 -> i=0 拇指
        x = bx0 + pos * (box + gap)
        if states[i]:
            cv2.rectangle(base, (x, by0), (x + box, by0 + box), COLOR_FINGER_ON, -1)
        else:
            cv2.rectangle(base, (x, by0), (x + box, by0 + box), COLOR_FINGER_OFF,
                          int(FINGER_BOX_THICKNESS))
        # ⚠️ 方块下面用 cv2.putText 画 **ASCII 缩写**（T/I/M/R/P）：
        #    中文必须借 PIL，而 5 个方块各做一次 PIL 往返要好几个毫秒 × 5，太慢。
        #    完整中文名放在下面信息面板里**一次性**写。
        cv2.putText(base, FINGER_BOX_TAGS[i], (x + int(box * 0.32), by0 + box + 24),
                    cv2.FONT_HERSHEY_SIMPLEX, 0.62, COLOR_LABEL, 2, cv2.LINE_AA)
    squares_bottom = by0 + box + 36
    if not settled:
        # 黄虚线框 = 手还在动，下面显示的是"保持值"
        total_w = 5 * box + 4 * gap
        _draw_dashed_rect(base, (bx0 - 8, by0 - 8), (bx0 + total_w + 8, by0 + box + 34),
                          COLOR_UNSETTLED, dash=14, thickness=3)

    palm_rel = result.get("palm_rel", (0.0, 0.0))

    hud_lines = []
    if not settled:
        message = ("过渡中：保持上一次稳定的判定" if result.get("held")
                   else "等待稳定：当前为临时识别结果")
        hud_lines.append((message, 18, COLOR_UNSETTLED))
    hud_lines.append(("手指: %s" % result.get("finger_text", "?"), 24, (0, 230, 255)))
    # 连续量也显示出来：调门槛时一眼看出余量够不够（单位是 R 的倍数）
    hud_lines.append((("局部长度 " if using_geometry else "延伸 ") + "  ".join("%.1f" % e for e in extensions),
                      16, (185, 185, 185)))
    hud_lines.append((("局部指轴定位身份，宽度与细长程度判断伸缩" if using_geometry
                       else "状态由模板匹配决定；延伸长度为辅助量"), 15, (150, 150, 150)))
    hud_lines.append((" ", 8, (0, 0, 0)))                                      # 空行分隔
    hud_lines.append(("fingers %d    gaps %d" % (result["finger_count"], len(result["gaps"])),
                      18, COLOR_LABEL))
    hud_lines.append(("solidity %.2f    span %.0f deg"
                      % (result.get("solidity", 0.0), result.get("angle_span_deg", 0.0)),
                      18, COLOR_LABEL))
    hud_lines.append(("R %.0f px    mean len %.2fR"
                      % (radius, result.get("mean_length_ratio", 0.0)), 18, COLOR_LABEL))
    hud_lines.append(("palm rel (%.2f, %.2f)" % palm_rel, 18, COLOR_LABEL))
    if wrist is not None:
        hud_lines.append(("wrist (%d, %d)" % (int(wrist[0]), int(wrist[1])), 18, COLOR_LABEL))
    else:
        hud_lines.append(("wrist not found -> up = image up", 18, (180, 180, 180)))

    # ★ 文字面板改到**方块下面**（原来 anchor="top-left" 会和方块叠在一起）
    draw_text_lines(base, hud_lines, (int(HUD_MARGIN), int(squares_bottom)), panel=True)
    return base


def step_recognize_on_mask(frame: np.ndarray, state) -> np.ndarray:
    """模式 5：把识别结果画在当前（掩膜）画面上。"""
    base = frame.copy()
    return _draw_recognition(base, state.flags.get("recognize"))


def step_recognize_on_original(frame: np.ndarray, state) -> np.ndarray:
    """模式 6：把识别结果画在**原图**上。

    原图从 state.flags["segment_source_bgr"] 取（颜色阈值那一层存下来的），
    **不能用 state.raw_frame** —— 镜像开着的时候 raw_frame 没被翻，
    坐标会和掩膜错位，画出来的标注就偏了。
    """
    source = state.flags.get("segment_source_bgr")
    if source is None:
        source = state.raw_frame if getattr(state, "raw_frame", None) is not None else frame
    base = source.copy()
    return _draw_recognition(base, state.flags.get("recognize"))


# ===========================================================================
# 插件 2：把真正生效的 ROI 边界画出来 + 触边检查
# ===========================================================================
def step_roi_boundary(frame: np.ndarray, state) -> np.ndarray:
    """在当前结果上画出真正生效的 ROI 边界，并做触边检查。

    因为本插件排在二值化之后，画上去的边界不会被二值化吃掉，
    所以「你看到的框」就是「真正生效的框」。用 r 键可以实时开关。
    """
    enabled = roi_enabled_now(state)
    state.flags["roi_enabled"] = enabled          # 回写，让 r 键有个确定的初始值

    height, width = frame.shape[:2]
    x0, y0, x1, y1 = roi_rect_pixels((height, width))

    # 触边检查：只在 **ROI 真的生效** 且 "当前显示的确实是掩膜" 时才做。
    # 显示模式 1 是原图，任何像素都非零，做触边检查毫无意义（会把三条边全点亮）。
    has_mask = bool(state.flags.get("view_mode_has_mask", True))
    touched = find_touched_edges(frame, (height, width), enabled) \
        if (enabled and has_mask) else []
    state.flags["roi_touched"] = touched

    thickness = 3
    inset = thickness + 1
    # ★ ROI 关掉时**不画框** —— 否则会画一个"看着像限制、其实没生效"的框，反而误导。
    if enabled and ROI_DRAW_BOUNDARY:
        # 画边界。触边时用红色，正常用橙黄。
        #
        # ⚠️ 注意线宽是**以坐标为中心向两侧扩展**的：在 (x0,y0) 画厚度 3 的矩形，
        #    线会溢出到 x0-1 / y0-1，也就是 ROI 之外。测试时正是这一点让
        #    "ROI 外必须全黑"被破坏。所以这里把矩形**往里缩** thickness+1 像素画。
        color = COLOR_BOUNDARY_BAD if touched else COLOR_BOUNDARY
        cv2.rectangle(frame,
                      (x0 + inset, y0 + inset),
                      (x1 - 1 - inset, y1 - 1 - inset),
                      color, thickness)

    # ★★ 左下角的信息面板：**不管 ROI 开不开都要画**。
    #    ⚠️ 原来 ROI 关掉时这个函数直接 return，结果整个诊断面板（前景占比、
    #       场景自校准量、掌心 C/R）全都不显示 —— 而那正是调算法时最需要看的。
    #    ⚠️ 这里也**不再用 has_mask 包住**：那些统计量只要算出来了就该显示。
    #       默认显示模式 6（原图）的 has_mask 是 False，会被整块藏掉；
    #       而模式 1 根本没有掩膜、segment_stats 是空的，自然就跳过了。
    #    位置：ROI 生效时贴 ROI 左下角（那里正好是手臂入画处、底色深好认）；
    #          ROI 关掉时贴画面左下角。
    # ⚠️ 必须用 draw_text_lines 而不是 cv2.putText —— view_mode 是中文
    #    （"原图"/"掩膜"/"识别(原图)"…），cv2 的 Hershey 字体画中文只会出乱码。
    stats = state.flags.get("segment_stats") or {}
    text_lines = []
    if touched:
        text_lines.append(("TOUCHING ROI: %s" % ",".join(touched), 20, COLOR_BOUNDARY_BAD))
    if not enabled:
        text_lines.append(("ROI: off (整幅画面都参与识别)", 18, (0, 200, 255)))
    view_mode = state.flags.get("view_mode")
    if view_mode:
        text_lines.append(("view: %s" % view_mode, 18, COLOR_TEXT))
    piece = []
    method = stats.get("method")
    if method:
        piece.append("gray" if method == "gray" else "color(Cr/Cb)")
    if stats.get("cleaned"):
        piece.append("cleaned")
    if stats.get("reconstructed"):
        piece.append("recon")
    if piece:
        text_lines.append(("method: %s" % "+".join(piece), 18, COLOR_TEXT))
    ratio = stats.get("foreground_ratio")
    if ratio is not None:
        text_lines.append(("foreground %.1f%%" % (100.0 * ratio), 18, COLOR_TEXT))
    # ★ 场景自校准：把本帧的色度平移量和"最终生效的框"显示出来。
    #   换光照/换背景时一眼就能看出它在不在工作：平移量明显不是 0 就是在补。
    #   （平移量为 0 说明本帧光照和标定基准一致，框按原样用）
    shift = state.flags.get("scene_shift")
    box = state.flags.get("scene_box")
    if shift is not None and box is not None:
        d_cr, d_cb = shift
        if abs(d_cr) >= 1.0 or abs(d_cb) >= 1.0:
            text_lines.append(("scene shift dCr%+.0f dCb%+.0f -> Cr[%d,%d] Cb[%d,%d]"
                               % (d_cr, d_cb, box[0], box[1], box[2], box[3]),
                               18, (0, 200, 255)))
        else:
            text_lines.append(("scene shift none, Cr[%d,%d] Cb[%d,%d]"
                               % (box[0], box[1], box[2], box[3]), 18, COLOR_TEXT))
    # 背景色估计的细节（块级诊断），换取样方式时用来看它稳不稳
    bg_est = state.flags.get("scene_bg_estimate")
    if bg_est and bg_est.get("mode") == "ring":
        text_lines.append(("bg %s: %d 块 Cr%.0f (spread %.0f)"
                           % (bg_est.get("mode"), bg_est.get("tiles", 0),
                              bg_est.get("bg_cr") or 0, bg_est.get("spread_cr") or 0),
                           18, (200, 200, 200)))
    # 重建那一层额外把掌心和基准颜色显示出来，方便判断容差合不合适
    if stats.get("reconstructed"):
        palm = stats.get("palm_center")
        if palm is not None:
            palm_r = stats.get("palm_radius", 0.0)
            raw_r = stats.get("palm_radius_raw", palm_r)
            # 两个 R 差得多 -> 说明掩膜被割了口子、闭运算副本补救生效了，标出来
            if raw_r and abs(palm_r - raw_r) / raw_r > 0.10:
                text_lines.append(("palm C=(%d,%d) R=%.0f (raw %.0f, 已按闭运算补救)"
                                   % (palm[0], palm[1], palm_r, raw_r), 18, (0, 200, 255)))
            else:
                text_lines.append(("palm C=(%d,%d) R=%.0f" % (palm[0], palm[1], palm_r),
                                   18, COLOR_TEXT))
        color_base = stats.get("color_base")
        if color_base is not None:
            text_lines.append(("base Cr=%.0f Cb=%.0f Y=%.0f" % color_base, 18, COLOR_TEXT))

    if text_lines:
        line_h = 26
        block_h = line_h * len(text_lines) + 8
        if enabled:
            anchor_x, anchor_bottom = x0 + inset + 8, y1 - inset - 14
        else:
            anchor_x, anchor_bottom = inset + 8, height - inset - 14
        text_top = max(inset + 8, anchor_bottom - block_h)
        # panel=True：小字号中文笔画密，靠黑描边会糊成一团，改用底衬面板
        draw_text_lines(frame, text_lines, (anchor_x, text_top), panel=True)

    # ★兜底保证：**掩膜模式下**，ROI 之外一律擦回黑色。
    #   这样"ROI 外全黑"就是结构性成立的，以后再加标注也不会破坏它。
    #   ⚠️ 必须只对掩膜做：显示模式 1 是原图，把外面擦黑它就不是原图了。
    #   （单测时踩到过这个坑：原图模式下 ROI 外被擦黑，6.4M 像素不对。）
    if has_mask:
        cv2.bitwise_and(frame, build_roi_mask_bgr((height, width), enabled), dst=frame)
    return frame


# ===========================================================================
#  ★★ 前处理：把手的方向转成「手指朝上」★★
# ===========================================================================
# 为什么需要：
#   整条流水线（手腕 = "下方最窄行"、截前臂、掌轴、所有角度判据）**都写死了
#   "小臂从画面下方入画、手指朝上"** ✓ 这是它 86% 的来源。
#   手一旦整体转 90°（比如"手掌朝镜头但手指朝左"），这条流水线就全错 ✗
#
# ★ 解法不是把每个判据都改成旋转无关（试过，反而更差 ✗），
#   而是**在投入计算前先判断手朝哪边，把画面转正**，再走原来那条流水线 ✓
#
# 怎么做（不看颜色以外的东西，成本约 3~5 ms）：
#   ① 把画面缩到 320 宽，用当前颜色阈值粗分割一次
#   ② 取最大的连通域（手 + 小臂），算它的**主成分方向**（PCA）
#      小臂是细长结构，会把主轴拉向自己 -> 主轴 ≈ 小臂/手指的连线方向 ✓
#   ③ 方向的正负：掌心（距离变换最大值点）在**手指那一侧**，
#      而掩膜质心偏向**小臂那一侧**（小臂有质量）-> 从掌心指向质心就是小臂方向 ✓
#   ④ 要转的角度 = 让小臂指向"画面下方"所需的旋转量 ✓
#
# ⚠️ 判不准时的兜底：找不到足够大的连通域就**不转**（角度 0）✓
AUTO_ROTATE = True               # 总开关
AUTO_ROTATE_DOWNSCALE = 320      # 判方向时把画面缩到这么宽（省时间）
# ★ 判方向时颜色阈值放宽多少（Cr/Cb 上下各放宽这么多）★
#   小臂常在阴影里、颜色和手掌差一截 ✗ 不放宽的话"手和小臂之间会断掉" -> 判不出方向
#   放宽只影响判方向这一步，不影响识别 ✓
AUTO_ROTATE_COLOR_SLACK = 0
# ★ 判"小臂从哪条边进来"时的门槛（看掩膜贴在哪条边上）★
#   贴边像素太少 -> 那条边不可信；贴边像素太多 -> 整条边都是掩膜（手贴边/分割糊了）也不可信
AUTO_ROTATE_EDGE_MIN_PIXELS = 3
AUTO_ROTATE_EDGE_MAX_FRAC = 0.35
# 判不出来时的兜底：写死一个角度。
#   ⚠️ 实测这批素材小臂都从**右边**进来 -> 要转 −90°。
#      如果判断器不可靠，就把 AUTO_ROTATE 关掉、用这个固定角度 ✓
AUTO_ROTATE_FIXED_DEG = -90.0
AUTO_ROTATE_USE_FIXED = False    # True = 不判断，永远用上面那个固定角度
AUTO_ROTATE_MIN_AREA = 0.004     # 最大连通域小于画面这个比例就不判（太小不可信）
AUTO_ROTATE_MAX_DEG = 120.0      # 要转的角度超过这个值就认为判错了，不转
AUTO_ROTATE_SMOOTH = 0.0         # 视频模式下角度的平滑系数（0=不平滑，越大越粘）

_ROTATE_STATE = {"angle": 0.0, "locked": False}


def reset_auto_rotate() -> None:
    """清掉自动转正的记忆（换图/换源时调用）。"""
    _ROTATE_STATE["angle"] = 0.0
    _ROTATE_STATE["locked"] = False


def detect_hand_rotation(frame: np.ndarray) -> float:
    """★ 判断"要把画面转多少度，手才会变成手指朝上"。返回角度（度，正=逆时针）。

    判不出来时返回 0.0（= 不转，按原样走）✓
    """
    h, w = frame.shape[:2]
    if h < 32 or w < 32:
        return 0.0
    scale = float(AUTO_ROTATE_DOWNSCALE) / max(1, w)
    small = cv2.resize(frame, (max(32, int(w * scale)), max(32, int(h * scale))),
                       interpolation=cv2.INTER_AREA)
    ycc = cv2.cvtColor(small, cv2.COLOR_BGR2YCrCb)
    # ★ 判方向时**故意放宽颜色阈值** ★
    #   ⚠️ 为什么要放宽：小臂常常在阴影里、颜色和手掌差一截 ✗
    #      用正常阈值时"手和小臂之间会断掉" -> 射线走不出去 -> 判不出方向 ✗
    #      实测：40 张里有 10 张因此判不出（它们的掩膜都很大，不是没分割出来）✓
    #   ⚠️ 放宽只影响**判方向这一步**，不影响后面的识别 ✓
    slack = float(AUTO_ROTATE_COLOR_SLACK)
    mask = cv2.inRange(ycc,
                       (int(Y_LOW), int(CR_LOW - slack), int(CB_LOW - slack)),
                       (int(Y_HIGH), int(CR_HIGH + slack), int(CB_HIGH + slack)))
    if int(np.count_nonzero(mask)) < 64:
        return 0.0
    count, labels, stats, _ = cv2.connectedComponentsWithStats(mask, 8)
    if count <= 1:
        return 0.0
    biggest = 1 + int(np.argmax(stats[1:, cv2.CC_STAT_AREA]))
    area = int(stats[biggest, cv2.CC_STAT_AREA])
    if area < float(AUTO_ROTATE_MIN_AREA) * mask.size:
        return 0.0
    blob = np.uint8(labels == biggest) * 255
    ys, xs = np.nonzero(blob)
    pts = np.stack([xs, ys], axis=1).astype(np.float64)

    # 掌心 = 距离变换最大值点（它一定在手掌里，也就是**手指那一侧**）
    dt = cv2.distanceTransform(blob, cv2.DIST_L2, 5)
    idx = int(np.argmax(dt))
    cy, cx = divmod(idx, blob.shape[1])
    palm = np.array([float(cx), float(cy)])

    # ★★★ 判据：小臂一定被【照片的某一条边】截断 ★★★
    #   所以只看"掩膜贴在哪条边上"，就知道小臂从哪边进来 ✓
    #   ⚠️ 之前那 6 版都在"猜小臂方向"（PCA / 质心 / 走得远 / 宽度带 / 角宽度），
    #      全是在面对结果调阈值 ✗ 这一版只看**掩膜和哪条边相连** —— 物理事实 ✓
    bh, bw = blob.shape[:2]
    edge_lines = {
        "left":   blob[:, 0],
        "right":  blob[:, bw - 1],
        "top":    blob[0, :],
        "bottom": blob[bh - 1, :],
    }
    best_edge, best_cnt, best_pos = None, 0, 0.0
    for name, line in edge_lines.items():
        idx = np.nonzero(line)[0]
        if idx.size > best_cnt:
            best_cnt = int(idx.size)
            best_edge = name
            best_pos = float(idx.mean())                # 接触带的中点（沿边坐标）
    if best_edge is None or best_cnt < int(AUTO_ROTATE_EDGE_MIN_PIXELS):
        return 0.0
    # 接触带太长 -> 整条边都是掩膜（手贴边或分割糊了），不可信
    if best_cnt > float(AUTO_ROTATE_EDGE_MAX_FRAC) * max(bh, bw):
        return 0.0

    dt = cv2.distanceTransform(blob, cv2.DIST_L2, 5)
    ys, xs = np.nonzero(blob)
    # 用【掩膜质心】而不是掌心：质心更稳，而且一定偏在小臂那一侧 ✓
    centroid = np.array([float(xs.mean()), float(ys.mean())])

    # 小臂方向 = 从质心指向"那条边的接触带中点"
    if best_edge == "left":
        target = np.array([0.0, best_pos])
    elif best_edge == "right":
        target = np.array([float(bw - 1), best_pos])
    elif best_edge == "top":
        target = np.array([best_pos, 0.0])
    else:
        target = np.array([best_pos, float(bh - 1)])
    arm = target - centroid
    n = float(np.linalg.norm(arm))
    if n < 1e-6:
        return 0.0
    arm = arm / n

    # 要转多少度，才能让"小臂进来的那条边"落到画面下方
    #   目标：小臂方向 = (0, +1)（图像坐标 y 向下）
    #   getRotationMatrix2D 正角度 = 逆时针 ✓
    #   实测：小臂从右边进来（掩膜贴右边）-> 要转 −90° ✓
    cur = float(np.degrees(np.arctan2(arm[0], arm[1])))
    while cur > 180.0:
        cur -= 360.0
    while cur < -180.0:
        cur += 360.0
    return float(-cur)


def auto_rotate_frame(frame: np.ndarray):
    """★ 前处理入口：判断方向 -> 转正。返回 ``(转正后的画面, 转过的角度)``。

    ⚠️ 转正之后，后面的流水线才能假设"小臂从下方入画" ✓
    """
    if not AUTO_ROTATE:
        return frame, 0.0
    if AUTO_ROTATE_USE_FIXED:
        angle = float(AUTO_ROTATE_FIXED_DEG)
    else:
        angle = detect_hand_rotation(frame)
    if AUTO_ROTATE_SMOOTH > 0.0 and _ROTATE_STATE["locked"]:
        a = float(AUTO_ROTATE_SMOOTH)
        angle = (1.0 - a) * angle + a * float(_ROTATE_STATE["angle"])
    _ROTATE_STATE["angle"] = angle
    _ROTATE_STATE["locked"] = True
    if abs(angle) < 1.0:
        return frame, angle
    h, w = frame.shape[:2]
    center = (w * 0.5, h * 0.5)
    m = cv2.getRotationMatrix2D(center, angle, 1.0)
    cos_a, sin_a = abs(m[0, 0]), abs(m[0, 1])
    nw = int(h * sin_a + w * cos_a)
    nh = int(h * cos_a + w * sin_a)
    m[0, 2] += nw * 0.5 - center[0]
    m[1, 2] += nh * 0.5 - center[1]
    out = cv2.warpAffine(frame, m, (nw, nh), flags=cv2.INTER_LINEAR,
                         borderMode=cv2.BORDER_REPLICATE)
    return out, angle


# ===========================================================================
# 用户实测的观察：**手在摆造型的那些过渡帧**会判错，而**手摆好不动的帧基本能认对** ✓
# 所以：不稳定的帧**不更新输出**，保持上一次稳定时的判定；连续若干帧稳定了才认。
#
# ★ 为什么这样比"复杂拒判机制"更该先做：
#   过渡帧的错**主要来自手在动**（运动模糊、掩膜在变），不是"看不清" ✗
#   而"手在不在动"用**帧间差异**就直接量得出来 —— 不需要识别层加任何新判据 ✓
#   （用户自己也提过同一思路："用检测像素整体变化来做延迟来近似照片"）
#
# 做法（全部很便宜，约 1 ms）：
#   ① ROI 内**隔 8 像素采样**再缩到 64x64 灰度
#   ② 与上一帧比，算平均绝对差 = 运动量
#   ③ 运动量 <= STABLE_DIFF_MAX 算"稳"；连续 STABLE_MIN_FRAMES 帧稳 -> 认为手摆好了
#   ④ 手摆好了才把这一帧的判定记下来
#   ⑤ 没摆好时：把判定**替换成上次记下的**，打 held=True 标记
#
# ⚠️ 这只是**门控**，不改变识别本身 —— 稳定帧的判定和以前完全一样 ✓
STABILITY_GATE = True
STABLE_DIFF_MAX = 2.0        # 平均绝对差（0~255）小于这个值算"稳"。越大越宽松
STABLE_MIN_FRAMES = 3        # 连续几帧稳才算"手摆好了"
STABLE_SAMPLE_STEP = 8       # 采样步长（越大越快、越不敏感）

_STABILITY = {"prev": None, "count": 0, "last": None}


def reset_stability() -> None:
    """清空稳定性门控的记忆（换图 / 换输入源时该调用）。"""
    _STABILITY["prev"] = None
    _STABILITY["count"] = 0
    _STABILITY["last"] = None


def step_stability_gate(frame: np.ndarray, state) -> Optional[np.ndarray]:
    """★ 过渡帧不出结论：不稳定时保持上一次稳定时的判定。

    必须排在 ``hand_recognize`` **之后**（要读它的结果），
    并排在绘制类插件**之前**（要先把结果换掉，绘制才画的是保持值）。

    ⚠️ 用 ``state.raw_frame`` 算运动量，**不用 ``frame``** ——
       跑到这一步时 ``frame`` 已经被前面的插件变成掩膜了，拿它算帧间差没意义 ✗
    """
    raw = getattr(state, "raw_frame", None)
    if raw is None or getattr(raw, "ndim", 0) != 3:
        return frame

    # ---- ① ROI 内隔点采样 + 缩到 64x64 灰度 ----
    height, width = raw.shape[:2]
    if roi_enabled_now(state):
        x0, y0, x1, y1 = roi_rect_pixels((height, width))
    else:
        x0, y0, x1, y1 = 0, 0, width, height
    step = int(max(1, STABLE_SAMPLE_STEP))
    patch = raw[y0:y1:step, x0:x1:step]
    if patch.size == 0:
        patch = raw[::step, ::step]
    try:
        gray = cv2.cvtColor(patch, cv2.COLOR_BGR2GRAY)
    except cv2.error:
        return frame
    small = cv2.resize(gray, (64, 64), interpolation=cv2.INTER_AREA)

    # ---- ② 与上一帧比 ----
    prev = _STABILITY["prev"]
    if prev is None:
        diff = 0.0
    else:
        diff = float(np.mean(np.abs(small.astype(np.int16) - prev.astype(np.int16))))
    _STABILITY["prev"] = small

    # ---- ③ 连续稳帧计数 ----
    if diff <= float(STABLE_DIFF_MAX):
        _STABILITY["count"] = int(_STABILITY["count"]) + 1
    else:
        _STABILITY["count"] = 0
    settled = bool(_STABILITY["count"] >= int(STABLE_MIN_FRAMES))

    # ---- ④ 稳了就把这一帧的判定记下来 ----
    rec = state.flags.get("recognize")
    if settled and rec is not None:
        _STABILITY["last"] = {
            "states": list(rec.get("finger_states") or []),
            "extensions": list(rec.get("finger_extensions") or []),
            "text": rec.get("finger_text"),
        }

    state.flags["motion_diff"] = round(diff, 2)
    state.flags["stable_count"] = int(_STABILITY["count"])
    state.flags["settled"] = settled
    if rec is not None:
        # 顺带把"这帧稳不稳"塞进结果里 —— 绘制插件拿不到 state，只能从这里读
        rec = dict(rec)
        rec["settled"] = settled
        rec["motion_diff"] = round(diff, 2)
        state.flags["recognize"] = rec

    # ---- ⑤ 没摆好：把判定换成"上次记下的"，打 held 标记 ----
    last = _STABILITY["last"]
    if rec is not None and not settled and last is not None:
        rec = dict(rec)
        rec["finger_states"] = list(last["states"])
        rec["finger_extensions"] = list(last["extensions"])
        rec["finger_text"] = last["text"]
        rec["held"] = True
        state.flags["recognize"] = rec
    return frame


def register(api) -> None:
    """main.py 会调用这个函数，把本模块的处理函数注册进插件链。

    注册顺序就是执行顺序。main.py 的 VIEW_MODES 会按 1/2/3 键
    启用不同的组合（靠 PluginRegistry.enable 实现）：
        1 -> 全都关掉，画面就是原图
        2 -> 只开 color_threshold，看到的是原始掩膜
        3 -> 再开 mask_cleanup，看到的是清理后的掩膜
    """
    # 灰度版按你的要求停用（注册着、代码保留，不进任何模式）
    api.add(PLUGIN_NAME, step_gray_threshold, enabled=GRAY_ENABLED_DEFAULT)
    # 颜色阈值（模式 2 / 3 / 4 用）
    api.add(COLOR_PLUGIN_NAME, step_color_threshold, enabled=COLOR_ENABLED_DEFAULT)
    # 清理：开运算 + 面积过滤 + 填洞（模式 3 / 4 用），必须排在颜色阈值之后
    api.add(CLEANUP_PLUGIN_NAME, step_mask_cleanup, enabled=CLEANUP_ENABLED_DEFAULT)
    # 掌心重建（模式 4 / 5 / 6 用），必须排在清理之后 —— 它要靠清理后的单连通域算掌心
    api.add(RECON_PLUGIN_NAME, step_palm_reconstruct, enabled=RECON_ENABLED_DEFAULT)
    # 识别骨架：截前臂 + 指尖 + 指缝（模式 5 / 6 用），只算不画
    api.add(RECOG_PLUGIN_NAME, step_hand_recognize, enabled=RECOG_ENABLED_DEFAULT)
    # ★ 稳定性门控：必须排在 hand_recognize【之后】（要读它的结果）、
    #   排在绘制类插件【之前】（要先把结果换成"保持值"，绘制才画得对）。
    api.add(STABILITY_PLUGIN_NAME, step_stability_gate, enabled=STABILITY_GATE)
    # Draw the result AFTER the temporal gate has selected the output states.
    api.add(DRAW_MASK_PLUGIN_NAME, step_recognize_on_mask, enabled=DRAW_ENABLED_DEFAULT)
    api.add(DRAW_ORIG_PLUGIN_NAME, step_recognize_on_original, enabled=DRAW_ENABLED_DEFAULT)
    # 画边界 + 触边检查（排在最后，画在结果之上）
    api.add(ROI_PLUGIN_NAME, step_roi_boundary, enabled=True)
