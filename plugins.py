#    注意：**掌心核心在任何设置下都是 100%**，所以调这个不影响掌心定位。
#
#  ⚠️ 剩下一部分影子去不掉是**颜色信息本身的天花板**：手的浅色/高光部分和布
#     在颜色上重叠，任何纯颜色方法都要在"去影子"和"保手指"之间做权衡。
