# ★★ 下界同样重要 ★★
#   ⚠️ 踩过的坑：只设上界时，**手指**也会被当成小臂 ✗
#      因为手指同样"细长"，而且当小臂被画面切短时，手指反而走得更远 ✗
#      实测 40 张里有 12 张因此判反了方向（+90° 而不是 −90°）✗
