# ===========================================================================
#
#   ★★★★★  第三部分：颜色阈值（YCbCr 的 Cr / Cb）就在这里改  ★★★★★
#
# ===========================================================================
#
#  判据（三个条件必须同时满足才算前景=白）：
#      CR_LOW <= Cr <= CR_HIGH
#      CB_LOW <= Cb <= CB_HIGH
#      Y_LOW  <= Y  <= Y_HIGH
#
#  为什么用 YCbCr 而不是灰度/RGB：
#    YCbCr 把「亮度 Y」和「颜色 Cr/Cb」拆开了，所以判「是什么颜色」不受明暗影响。
#    阴影主要改 Y、基本不改 Cr/Cb —— 这正是它能救「手上自阴影导致掩膜出洞」的原因。
#    实测（shou1.png）：灰度对「手 vs 布」的可分性 d'=0.74（基本没用），
#    Cr/Cb 色度是 d'=1.45（静态图像里最好的判据）。
#
#  ⚠️ 通道顺序的坑：
#    cv2.COLOR_BGR2YCrCb 返回的三通道是 **Y, Cr, Cb**
#    （函数名写的是 YCrCb，所以第 1 个通道是 Cr、第 2 个是 Cb），别取反了。
#
# ---------------------------------------------------------------------------
#  调参参考：shou1.png 里各区域实测的 Cr / Cb
# ---------------------------------------------------------------------------
#      区域           Cr       Cb
#      掌心(偏红)    147.9    122.0
#      手掌中部      144.9    118.4
#      拇指          136.2    122.3
#      米白布-左     125.0    130.5     <- 布很中性：Cr 偏低、Cb 偏高
#      米白布-中     124.0    129.5
#      黄T恤         150.0     72.6     <- Cb 极低，靠 Cb 下限排掉
#      纸箱          136.0    107.3     <- 和肤色重叠！颜色分不开，只能靠 ROI 排掉
#      键盘          127.0    129.5
#      下巴/脸       146.6    110.9
#
#  调参思路（关键）：
#    * 手 Cb≈118~123，布 Cb≈129~131  ->  **Cb 上限压到 126~127 就能把布挡掉**
#    * 手 Cr≈136~148，布 Cr≈124~126  ->  **Cr 下限抬到 131~133 也能把布挡掉**
#    两个边界各自都能挡布，所以这个判据相对灰度是「双重保险」。
#    * 想更严（少误检）就把 CR_LOW 往上抬、CB_HIGH 往下压
#    * 想更松（少漏检）就反过来
#    * 手的一部分（如偏白的手指）漏了 -> 说明 CR_LOW 抬太高 或 CB_HIGH 压太狠
#
#  ⚠️ 每一对同样要求 下限 <= 上限，写反了会自动交换并打印提示。
# ---------------------------------------------------------------------------
CR_LOW = 131
CR_HIGH = 173
CB_LOW = 77
CB_HIGH = 128
Y_LOW = 40
Y_HIGH = 245

# ---------------------------------------------------------------------------
#  ★★ 场景色度自校准（B 方案）—— 让上面这组"绝对阈值"能跟着光照平移  ★★
#
#  ⚠️ 为什么必须要这个：
#     上面 CR_LOW=131 / CB_HIGH=128 这组值是在「明亮白光 + 白板/桌面」下标定的。
#     第三批素材（印花床单 + 暗暖光）实测，ROI 内**背景**的色度中位数是：
#          Cr 127.0 -> 139.3     Cb 128.0 -> 119.1
#     也就是说背景整体平移了 (+12, -9)。原来它恰好卡在 CR_LOW=131 **外面**，
#     平移之后就整个挪进肤色框里了 —— 后果：
#          原始阈值前景   14.7% -> 77.5%
#          噪声连通域       15 -> 341
#     掩膜糊成一片，下游的清理/重建再努力也救不回来（掌心都是从一个糊掉的
#     掩膜里估出来的）。
#
#  ★ 而且实测"单纯抬高 CR_LOW"没用 —— 131 已经是三批合计最优：
#         CR_LOW     131   135   140   144   148
#         s1         9/9   9/9   9/9   8/9   8/9
#         s2         9/9   9/9   8/9   6/9   7/9
#         s3         4/10  4/10  3/10  3/10  3/10
#        三批合计   22    22    20    17    18
#     原因：**手的色度也跟着平移了**。抬阈值在切背景的同时也把手切掉了。
#
#  ★ 所以正确做法不是改数值，而是**把整个框按本帧估计的平移量一起挪**：
#     光照整体变化时，背景和肤色的色度是**一起平移**的；按同一个位移量平移
#     肤色框，"背景在框外、手在框内"这个相对关系就恢复了。
SCENE_CALIBRATE = True          # 关掉就退回原来的写死绝对阈值
# 标定基准 = 中性背景在"标准光照"下的 Cr/Cb。
# 实测值就是 s1（白板/桌面，明亮白光）的 ROI 中位数，所以基准场景下位移为 0。
SCENE_BASELINE_CR = 127.0
SCENE_BASELINE_CB = 128.0
# 位移限幅：背景估计万一跑飞，最多平移这么多，防止把框拖到毫无意义的位置
SCENE_SHIFT_CLAMP = 22.0
# 估计背景色度时的下采样步长（每隔几行/列取一个点，避免每帧算 100 万像素的中位数）
SCENE_ESTIMATE_STEP = 4

# --- ★ 背景取样位置：从"整个 ROI"改成"三边环带 + 分块表决" -------------------
#
# ⚠️ 为什么必须改（实测翻车）：
#    原来取 **ROI 内所有像素** 的 Cr/Cb 中位数当背景色，隐含假设"背景占一半以上"。
#    静态图里手只占 10~15%，假设勉强成立；**但视频里手占了 ROI 的 24~37%** ——
#    中位数被手拽偏：实测 frame 40 真实背景 Cr=137，而 ROI 中位数算出 **142**。
#    平移方向估错 -> 肤色框被挪到反方向 -> 越校准越糟 -> 掩膜糊成一片。
#    这是**"取样位置"的结构性错误，不是阈值数值问题**。
#
# ★ 改法：不再从整个 ROI 取样，改为从"手几乎不可能出现的**边缘环带**"取样；
#    并且把每条边**切成若干小块分别估计、再对块结果取中位数（多数表决）**。
#    底层逻辑：把"一个容易被整体污染的大估计"拆成"很多个局部小估计 + 多数表决"，
#    污染从"按比例毒化整体"变成"要么整个丢掉一个局部、要么完全不丢"。
#
# ★ 为什么只用上、左、右三条边：**小臂从画面下方入画**（触边检查故意不查下边
#    就是同一个原因），下边环带会被小臂长期占住，取样无意义。
#  ★ **但实测结论：ring 反而更差，所以默认改回 "roi"**（保留代码和开关，随时对照）：
#      配置              静态图 28 张   视频 8 帧   frame40 前景
#      roi（旧）            28/28 ✓      1/8        42%
#      ring P50（原方案）    23/28 ✗      0/8        46%
#      ring P25             23/28 ✗      0/8        48%
#      ring P15             28/28 ✓      1/8        45%
#    为什么失败（实测查清）：这个方案假设"边缘环带手几乎不出现"，但——
#      · 视频里手很大，**直接压在 ROI 右边带上**（右侧 4~5 个块是手）
#      · 更要命的是：**环带量的那片背景本身就有大块"肤色"** ——
#        床单的粉色印花。frame 40 的块级数据（Cr / Y）：
#            印花块  Cr 147~155   Y 134~157   <- 亮
#            手块    Cr 157~159   Y  71~115   <- 暗
#        Cr 上两者**几乎重合**，所以"把背景估计修准"这件事本身没有意义 ——
#        修准了也分不开，反而把框往错的方向挪（前景 42% -> 48%）。
#    ★ 真正的缺口是**亮度 Y**：手的 Y 干净地低于背景（这里 71~115 vs 134~157，
#      中间在 Y≈120~130 有空隙）。Y 是**正交线索**，现在的 Y 区间是 [40,245]，
#      等于完全没用上。这是下一步该做的（见交接文档第 8 节问题 2 方案 A）。
SCENE_SAMPLE_MODE = "roi"       # "roi" = 整幅 ROI 中位数（实测最好，默认）/ "ring" = 三边环带分块表决（实验性，实测更差）
SCENE_RING_FRAC = 0.12          # 环带宽度 = 对应边长的这个比例
SCENE_RING_TILES = 8            # 每条边切成几段（共 3 × 8 = 24 个取样块）
SCENE_RING_MIN_TILES = 4        # 有效块少于这个数就退回旧行为（极端帧的兜底）
# ★ 汇总 24 个块时取哪个分位数。
#   ⚠️ 实测教训：用 **50（中位数）不行** —— 这个方案假设"边缘环带手几乎不出现"，
#      但实测视频里手很大、**直接压在 ROI 右边带上**：24 个块里 7~8 个被污染
#      （背景块 Cr 130~137，手块 147~159）。污染超过一半时中位数也救不了，
#      估计值被抬高 -> dCr 变大 -> 框挪多了 -> **前景反而更糊**。
#   ★ 所以改成取**偏低的那一簇**：手的 Cr 比背景**高**，所以背景在块分布的**低端**。
#      取 25 分位数就稳定落在背景簇里（实测见 NOTES/CHANGELOG）。
#      ⚠️ 不能无脑取最小值：个别块可能是阴影/暗角，取分位数比取极值稳。
SCENE_TILE_PERCENTILE = 25.0    # 50 = 中位数（原方案）/ 25 = 背景簇（推荐）
